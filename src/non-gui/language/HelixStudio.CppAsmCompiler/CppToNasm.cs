using System;
using System.Collections.Generic;
using System.Text;
using HelixPythonNamespace.CudaVirtualCompiler.Ast;
using HelixPythonNamespace.CudaVirtualCompiler.Lexing;
using HelixPythonNamespace.CudaVirtualCompiler.Parsing;

namespace HelixPythonNamespace.CppAsmCompiler
{
    /// <summary>
    /// Translates a subset of C++ into NASM (win64).
    ///
    /// Supported: free functions whose parameters and return type are <c>int</c> or <c>double</c>;
    /// integer and IEEE-754 arithmetic, bitwise and shift operators, comparisons and the
    /// short-circuit operators; <c>if</c>/<c>else</c>, <c>while</c>, <c>do</c>/<c>while</c>,
    /// <c>for</c>, <c>break</c>/<c>continue</c>; local variables with initialisers; <c>++</c>,
    /// <c>--</c> and the compound assignments; casts between the two types; the conditional
    /// operator; and calls between the file's own functions, recursion included. Everything else
    /// is refused with a reason and a line.
    ///
    /// The subset boundary is not arbitrary: it is exactly the code that needs no runtime.
    /// Classes need constructors and vtables, exceptions need unwind tables, templates need
    /// instantiation, <c>new</c> and the STL need a heap, and pointers need a memory model —
    /// none of which exist in bare assembly, and all of which a compiler must implement honestly
    /// or not claim.
    /// </summary>
    public static class CppToNasm
    {
        public static TranslationResult Translate(string source, string filePath = null)
        {
            if (string.IsNullOrWhiteSpace(source)) return TranslationResult.Refuse("empty source");

            var lexer = new CudaLexer(source, filePath ?? string.Empty);
            List<CudaToken> tokens = lexer.Tokenize();
            foreach (var d in lexer.Diagnostics)
                if (d.Severity >= HelixPythonNamespace.Python.Diagnostics.ParseSeverity.Error)
                    return TranslationResult.Refuse("source has lexical errors: " + d.Message,
                                                    d.Span.Start.Line);

            var parser = new CudaParser(tokens, filePath ?? string.Empty);
            TranslationUnit unit = parser.Parse();
            foreach (var d in parser.Diagnostics)
                if (d.Severity >= HelixPythonNamespace.Python.Diagnostics.ParseSeverity.Error)
                    return TranslationResult.Refuse("source has syntax errors: " + d.Message,
                                                    d.Span.Start.Line);
            if (unit == null) return TranslationResult.Refuse("source did not parse");

            var functions = new List<FunctionDecl>();
            foreach (Decl d in unit.Decls)
            {
                if (d is FunctionDecl fn)
                {
                    if (fn.Body == null) continue;              // a prototype declares, emits nothing
                    functions.Add(fn);
                    continue;
                }
                if (d is UsingNamespaceDecl || d is NamespaceAliasDecl || d is TypeAliasDecl) continue;
                return TranslationResult.Refuse(
                    "only function definitions are supported at file scope; found "
                    + Describe(d), d.Span.Start.Line);
            }
            if (functions.Count == 0) return TranslationResult.Refuse("no function definitions found");

            // Every signature is checked before any body is emitted, so a function may call one
            // defined later in the file — as it may in C++ given a prototype, and as recursion
            // through a pair of functions requires.
            var signatures = new Dictionary<string, CxxFunctionType>(StringComparer.Ordinal);
            foreach (FunctionDecl fn in functions)
            {
                CxxFunctionType signature;
                string reason = CheckSignature(fn, out signature);
                if (reason != null) return TranslationResult.Refuse(reason, fn.Span.Start.Line);
                if (signatures.ContainsKey(fn.Name))
                    return TranslationResult.Refuse(
                        "'" + fn.Name + "' is defined more than once; C++ would treat these as "
                        + "overloads, but an object file cannot hold two symbols of the same name "
                        + "and this translator does not mangle", fn.Span.Start.Line);
                signatures[fn.Name] = signature;
            }

            var text = new StringBuilder();
            text.AppendLine("; Generated by HelixPython (C++ -> NASM, win64).");
            text.AppendLine("; int is 32-bit in EAX, double is binary64 in XMM0. No heap, no runtime.");
            text.AppendLine("default rel");
            text.AppendLine("section .text");
            text.AppendLine();

            var names = new List<string>();
            var emitted = new List<TranslatedFunction>();
            foreach (FunctionDecl fn in functions)
            {
                CxxTypeTable types = CxxTypeTable.Build(fn, signatures[fn.Name]);
                if (types.Error != null) return TranslationResult.Refuse(types.Error, types.ErrorLine);

                var emitter = new Win64CxxEmitter(signatures);
                string asm = emitter.EmitFunction(fn, types);
                if (asm == null)
                    return TranslationResult.Refuse(emitter.Refusal, emitter.RefusalLine);
                text.Append(asm).AppendLine();
                names.Add(fn.Name);
                emitted.Add(Describe(signatures[fn.Name]));
            }
            return TranslationResult.Ok(text.ToString(), names, emitted);
        }

        private static string Describe(Decl d)
        {
            if (d is RecordDecl r) return "a " + r.Kind.ToString().ToLowerInvariant() + " definition";
            if (d is TemplateDecl) return "a template";
            if (d is NamespaceDecl) return "a namespace";
            if (d is EnumDecl) return "an enum";
            if (d is VarDecl v) return "the global variable '" + v.Name + "'";
            return d.GetType().Name;
        }

        private static TranslatedFunction Describe(CxxFunctionType t)
        {
            var parameters = new List<string>();
            foreach (VCxx p in t.Parameters) parameters.Add(CxxTypeTable.Describe(p));
            return new TranslatedFunction(t.Name, parameters, CxxTypeTable.Describe(t.Returns));
        }

        private static string CheckSignature(FunctionDecl fn, out CxxFunctionType signature)
        {
            signature = null;
            if (fn.Space != FuncSpace.Host)
                return "'" + fn.Name + "' is a CUDA " + fn.Space + " function; this translator "
                     + "targets the host CPU";
            if (!string.IsNullOrEmpty(fn.QualifiedName) && fn.QualifiedName != fn.Name)
                return "'" + fn.QualifiedName + "' is not at file scope; members and namespaced "
                     + "functions would need name mangling this translator does not do";

            var parameters = new List<VCxx>();
            foreach (Parameter p in fn.Params)
            {
                if (p.DefaultValue != null)
                    return "default argument values are not supported; the calling convention is "
                         + "positional and every argument must be supplied by the caller";
                if (string.IsNullOrEmpty(p.Name))
                    return "every parameter must be named for it to be given a frame slot";
                VCxx t;
                string why;
                if (!CxxTypeTable.TryType(p.Type, out t, out why))
                    return "parameter '" + p.Name + "': " + why;
                parameters.Add(t);
            }
            VCxx returns;
            string reason;
            if (!CxxTypeTable.TryType(fn.ReturnType, out returns, out reason))
                return "return type of '" + fn.Name + "': " + reason;

            signature = new CxxFunctionType(fn.Name, parameters, returns);
            return null;
        }
    }
}
