using System;
using System.Collections.Generic;
using System.Text;
using HelixPythonNamespace.VirtualCompiler.Ast;
using PyParser = HelixPythonNamespace.Python.Python;

namespace HelixPythonNamespace.PythonAsmCompiler
{
    /// <summary>
    /// Translates a statically-typed subset of Python into NASM (win64).
    ///
    /// Supported: module-level functions whose parameters and return are annotated <c>int</c> or
    /// <c>float</c>; integer and IEEE-754 arithmetic and comparisons; <c>if</c>/<c>elif</c>/
    /// <c>else</c>, <c>while</c>, <c>for i in range(...)</c>, <c>break</c>/<c>continue</c>; local
    /// variables including unpacking assignment; <c>int()</c> and <c>float()</c> conversions; and
    /// calls between the module's own functions, recursion included. Everything else is refused
    /// with a reason.
    ///
    /// The subset boundary is not arbitrary: it is exactly the code that needs no runtime. Lists,
    /// dicts, strings, objects, closures, generators and exceptions all require heap allocation,
    /// garbage collection or the object protocol, none of which exist in bare assembly.
    /// </summary>
    public static class PythonToNasm
    {
        private static readonly string[] ReservedNames = { "int", "float", "range" };

        public static TranslationResult Translate(string source, string filePath = null)
        {
            if (string.IsNullOrWhiteSpace(source)) return TranslationResult.Refuse("empty source");

            var parsed = PyParser.ParseModule(source, filePath ?? string.Empty);
            if (parsed == null || parsed.Module == null)
                return TranslationResult.Refuse("source did not parse");
            foreach (var d in parsed.Diagnostics)
                if (d.Severity >= HelixPythonNamespace.Python.Diagnostics.ParseSeverity.Error)
                    return TranslationResult.Refuse("source has syntax errors: " + d.Message, d.Span.Start.Line);

            Module module = CstToAst.Lower(parsed.Module);
            var functions = new List<FunctionDef>();
            foreach (Stmt s in module.Body)
            {
                if (s is FunctionDef fn) { functions.Add(fn); continue; }
                if (s is ImportFrom || s is Import || s is Pass) continue;
                if (s is ExprStmt es && es.Value is Constant) continue;   // module docstring
                return TranslationResult.Refuse(
                    "only function definitions are supported at module level; found "
                    + s.GetType().Name, s.Span.Start.Line);
            }
            if (functions.Count == 0) return TranslationResult.Refuse("no function definitions found");

            // Every signature is checked before any body is emitted, so a function may call one
            // that is defined later in the file — as it may in Python, where the name is resolved
            // when the call runs rather than when the def is read.
            var signatures = new Dictionary<string, FunctionType>(StringComparer.Ordinal);
            foreach (FunctionDef fn in functions)
            {
                FunctionType signature;
                string reason = CheckSignature(fn, out signature);
                if (reason != null) return TranslationResult.Refuse(reason, fn.Span.Start.Line);
                if (signatures.ContainsKey(fn.Name))
                    return TranslationResult.Refuse(
                        "'" + fn.Name + "' is defined more than once; the later definition would "
                        + "shadow the earlier one at run time, but an object file cannot hold two "
                        + "symbols of the same name", fn.Span.Start.Line);
                signatures[fn.Name] = signature;
            }

            var text = new StringBuilder();
            text.AppendLine("; Generated by HelixPython (Python -> NASM, win64).");
            text.AppendLine("; Integers in RAX, doubles in XMM0. No heap, no objects, no runtime.");
            text.AppendLine("default rel");
            text.AppendLine("section .text");
            text.AppendLine();

            var names = new List<string>();
            var emitted = new List<TranslatedFunction>();
            foreach (FunctionDef fn in functions)
            {
                int line;
                string unbound = LocalFlow.Check(fn, signatures.Keys, out line);
                if (unbound != null) return TranslationResult.Refuse(unbound, line);

                TypeTable types = TypeTable.Build(fn, signatures);
                if (types.Error != null) return TranslationResult.Refuse(types.Error, types.ErrorLine);

                var emitter = new Win64Emitter(signatures);
                string asm = emitter.EmitFunction(fn, types);
                if (asm == null)
                    return TranslationResult.Refuse(emitter.Refusal, emitter.RefusalLine);
                text.Append(asm).AppendLine();
                names.Add(fn.Name);
                emitted.Add(Describe(signatures[fn.Name]));
            }
            return TranslationResult.Ok(text.ToString(), names, emitted);
        }

        private static TranslatedFunction Describe(FunctionType t)
        {
            var parameters = new List<string>();
            foreach (VType p in t.Parameters) parameters.Add(TypeTable.Describe(p));
            return new TranslatedFunction(t.Name, parameters, TypeTable.Describe(t.Returns));
        }

        /// <summary>
        /// The subset is statically typed, so every parameter and the return must be annotated
        /// <c>int</c> or <c>float</c>. Without annotations the compiler cannot know whether
        /// <c>a + b</c> is an integer add, a double add, or a dynamic dispatch, and guessing is
        /// how a compiler silently miscompiles.
        /// </summary>
        private static string CheckSignature(FunctionDef fn, out FunctionType signature)
        {
            signature = null;
            if (Array.IndexOf(ReservedNames, fn.Name) >= 0)
                return "'" + fn.Name + "' is a built-in this compiler implements itself and cannot "
                     + "be redefined";
            if (fn.DecoratorList != null && fn.DecoratorList.Count > 0)
                return "decorators are not supported";
            if (fn.Args == null) return "function has no argument list";
            if ((fn.Args.VarArg != null) || (fn.Args.KwArg != null))
                return "*args / **kwargs are not supported";
            if (fn.Args.Defaults != null && fn.Args.Defaults.Count > 0)
                return "default argument values are not supported";
            if (fn.Args.KwOnlyArgs != null && fn.Args.KwOnlyArgs.Count > 0)
                return "keyword-only parameters are not supported; the calling convention is positional";
            // Positional-only parameters live in their own list. The emitter reads only Args, so
            // accepting them would silently drop the parameters instead of compiling them.
            if (fn.Args.PosOnlyArgs != null && fn.Args.PosOnlyArgs.Count > 0)
                return "positional-only parameters ('/') are not supported";

            var parameters = new List<VType>();
            if (fn.Args.Args != null)
            {
                foreach (Arg a in fn.Args.Args)
                {
                    VType t;
                    if (!TypeTable.TryAnnotation(a.Annotation, out t))
                        return "parameter '" + a.Name + "' must be annotated 'int' or 'float' (this "
                             + "subset is statically typed; a register holds one or the other)";
                    parameters.Add(t);
                }
            }
            VType returns;
            if (!TypeTable.TryAnnotation(fn.Returns, out returns))
                return "function '" + fn.Name + "' must declare '-> int' or '-> float'";

            signature = new FunctionType(fn.Name, parameters, returns);
            return null;
        }
    }
}
