using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using HelixPythonNamespace.Python.Syntax;

namespace HelixPythonNamespace.Workspace.PyToCpp
{
    /// <summary>
    /// Pass 2: mechanically emits C++ from a module that Pass 1's PythonToCppTypeChecker
    /// already checked successfully. Every expression's type comes from
    /// <see cref="PythonToCppTypeChecker.NodeTypes"/> — Pass 2 never re-derives a type or
    /// re-decides whether something is in scope; by construction everything here is already
    /// valid. The user's `def main()` becomes the literal C++ process entry point (matching
    /// the retired C pipeline's convention); the standard `if __name__ == "__main__": main()`
    /// guard (or an equivalent bare `main()` call) is a no-op Pass 1 already recognized and
    /// is not re-emitted.
    /// </summary>
    public sealed class PythonToCppEmitter
    {
        private readonly PythonToCppTypeChecker _checker;
        private readonly StringBuilder _sb = new StringBuilder();
        private int _tempCounter;

        // C++ reserved words that are NOT Python keywords (so a Python program could legally
        // use one as an identifier) — escaped with a trailing underscore on emission.
        private static readonly HashSet<string> CppOnlyReservedWords = new HashSet<string>(StringComparer.Ordinal)
        {
            "new", "delete", "template", "namespace", "typename", "friend", "virtual",
            "public", "private", "protected", "operator", "this", "sizeof", "typedef",
            "union", "struct", "enum", "explicit", "inline", "mutable", "const_cast",
            "static_cast", "dynamic_cast", "reinterpret_cast", "using", "auto", "register",
            "goto", "signed", "unsigned", "short", "long", "char", "wchar_t", "bool_t",
            "asm", "export", "extern", "volatile",
        };

        private static readonly Dictionary<string, string> BuiltinExceptionRuntimeNames = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["Exception"] = "pyrt::PyException", ["BaseException"] = "pyrt::PyException",
            ["ValueError"] = "pyrt::PyValueError", ["TypeError"] = "pyrt::PyTypeError",
            ["KeyError"] = "pyrt::PyKeyError", ["IndexError"] = "pyrt::PyIndexError",
            ["ZeroDivisionError"] = "pyrt::PyZeroDivisionError", ["OverflowError"] = "pyrt::PyOverflowError",
            ["AttributeError"] = "pyrt::PyAttributeError", ["RuntimeError"] = "pyrt::PyRuntimeError",
            ["NotImplementedError"] = "pyrt::PyNotImplementedError", ["AssertionError"] = "pyrt::PyAssertionError",
            ["StopIteration"] = "pyrt::PyStopIteration", ["NameError"] = "pyrt::PyNameError",
        };

        public PythonToCppEmitter(PythonToCppTypeChecker checker) { _checker = checker; }

        public string Emit(ModuleSyntax module)
        {
            _sb.Append("// Auto-generated by HelixStudio's Python -> C++ translator. Do not edit by hand.\n");
            _sb.Append("#include \"pyrt.hpp\"\n#include <iostream>\n\nusing namespace pyrt;\n\n");

            List<ClassDefSyntax> classes = module.Statements.OfType<ClassDefSyntax>().ToList();
            List<FunctionDefSyntax> freeFunctions = module.Statements.OfType<FunctionDefSyntax>().Where(f => f.Name != "main").ToList();
            FunctionDefSyntax mainFd = module.Statements.OfType<FunctionDefSyntax>().FirstOrDefault(f => f.Name == "main");

            foreach (ClassDefSyntax cd in classes) _sb.Append("class ").Append(Escape(cd.Name)).Append(";\n");
            if (classes.Count > 0) _sb.Append('\n');

            foreach (FunctionDefSyntax fd in freeFunctions) EmitFreeFunctionDeclaration(fd);
            if (freeFunctions.Count > 0) _sb.Append('\n');

            foreach (ClassDefSyntax cd in classes) EmitClass(cd);

            foreach (FunctionDefSyntax fd in freeFunctions) EmitFreeFunctionDefinition(fd);

            foreach (StatementSyntax s in module.Statements)
                if (s is AssignmentStatement asn) EmitGlobalVariable(asn);
            _sb.Append('\n');

            if (mainFd != null) EmitEntryPoint(mainFd);

            return _sb.ToString();
        }

        // ================================================================
        // Names / types
        // ================================================================

        private static string Escape(string pythonIdentifier) =>
            CppOnlyReservedWords.Contains(pythonIdentifier) ? pythonIdentifier + "_" : pythonIdentifier;

        private string TypeName(CppType t)
        {
            switch (t)
            {
                case PrimitiveType p when p.Name == "int": return "pyrt::py_int";
                case PrimitiveType p when p.Name == "float": return "pyrt::py_float";
                case PrimitiveType p when p.Name == "bool": return "pyrt::py_bool";
                case PrimitiveType p when p.Name == "str": return "pyrt::Str";
                case PrimitiveType p when p.Name == "None": return "void";
                case ListType l: return "pyrt::List<" + TypeName(l.Element) + ">";
                case DictType d: return "pyrt::Dict<" + TypeName(d.Key) + ", " + TypeName(d.Value) + ">";
                case SetType s: return "pyrt::Set<" + TypeName(s.Element) + ">";
                case TupleType tup: return "pyrt::Tuple<" + string.Join(", ", tup.Elements.Select(TypeName)) + ">";
                // shared_ptr is already nullable — None <-> nullptr needs no extra wrapper.
                case OptionalType opt when opt.Inner is ClassType: return TypeName(opt.Inner);
                case OptionalType opt: return "std::optional<" + TypeName(opt.Inner) + ">";
                // Exception classes are value types (thrown/caught by value/reference, C++'s
                // own idiom) — every other class instance is shared_ptr-backed for Python's
                // reference/aliasing semantics. See EmitCall's matching special case.
                case ClassType c when _checker.Classes.TryGetValue(c.Name, out ClassInfo ciExc) && ciExc.IsExceptionType:
                    return Escape(c.Name);
                case ClassType c: return "std::shared_ptr<" + Escape(c.Name) + ">";
                default: throw new NotSupportedException("PythonToCppEmitter: no C++ type mapping for " + t);
            }
        }

        private CppType TypeOf(ExpressionSyntax e) =>
            _checker.NodeTypes.TryGetValue(e, out CppType t) ? t : throw new InvalidOperationException(
                "PythonToCppEmitter: no resolved type for an expression Pass 1 should have typed (" + e.GetType().Name + ")");

        // ================================================================
        // Functions
        // ================================================================

        private string ParamList(FunctionInfo fi)
        {
            var parts = new List<string>();
            foreach (ParamInfo p in fi.Parameters)
            {
                CppType t = p.IsVarPositional ? new ListType(p.Type) : p.IsVarKeyword ? new DictType(CppType.Str, p.Type) : p.Type;
                parts.Add(TypeName(t) + " " + Escape(p.Name));
            }
            return string.Join(", ", parts);
        }

        private void EmitFreeFunctionDeclaration(FunctionDefSyntax fd)
        {
            FunctionInfo fi = _checker.Functions[fd.Name];
            _sb.Append(TypeName(fi.ReturnType)).Append(' ').Append(Escape(fd.Name)).Append('(').Append(ParamList(fi)).Append(");\n");
        }

        private void EmitFreeFunctionDefinition(FunctionDefSyntax fd)
        {
            FunctionInfo fi = _checker.Functions[fd.Name];
            _sb.Append(TypeName(fi.ReturnType)).Append(' ').Append(Escape(fd.Name)).Append('(').Append(ParamList(fi)).Append(") {\n");
            var declared = new HashSet<string>(fi.Parameters.Select(p => p.Name));
            EmitStatements(fd.Body?.Statements, 1, declared);
            _sb.Append("}\n\n");
        }

        // ================================================================
        // Classes
        // ================================================================

        // A derived class's Python base can be a builtin exception name ("Exception",
        // "ValueError", ...), which must resolve to its pyrt runtime class, not a
        // nonexistent user type of that name.
        private string ResolvedBaseCppName(string pythonBaseName) =>
            BuiltinExceptionRuntimeNames.TryGetValue(pythonBaseName, out string mapped) ? mapped : Escape(pythonBaseName);

        private void EmitClass(ClassDefSyntax cd)
        {
            ClassInfo ci = _checker.Classes[cd.Name];
            string baseCppName = ci.BaseClassName != null ? ResolvedBaseCppName(ci.BaseClassName) : null;

            _sb.Append("class ").Append(Escape(cd.Name));
            if (baseCppName != null) _sb.Append(" : public ").Append(baseCppName);
            _sb.Append(" {\npublic:\n");

            foreach (FieldInfo f in ci.Fields.Values)
                _sb.Append("    ").Append(TypeName(f.Type)).Append(' ').Append(Escape(f.Name)).Append(";\n");

            bool hasOwnInit = cd.Body?.Statements.OfType<FunctionDefSyntax>().Any(f => f.Name == "__init__") ?? false;
            if (!hasOwnInit && baseCppName != null)
            {
                // Inheriting-constructors syntax is `using <qualified-base>::<UNqualified-name>;`
                // — the trailing member-name segment must not repeat any namespace qualifier
                // (pyrt::PyException's own unqualified name is just PyException).
                string unqualifiedBaseName = baseCppName.Contains("::") ? baseCppName.Substring(baseCppName.LastIndexOf("::", StringComparison.Ordinal) + 2) : baseCppName;
                _sb.Append("    using ").Append(baseCppName).Append("::").Append(unqualifiedBaseName).Append(";\n");
            }

            foreach (StatementSyntax member in cd.Body?.Statements ?? Array.Empty<StatementSyntax>())
            {
                if (!(member is FunctionDefSyntax fd)) continue;
                if (fd.Name == "__init__") EmitConstructor(cd, ci, fd);
                else EmitMethod(ci, fd);
            }

            _sb.Append("};\n\n");
        }

        private void EmitConstructor(ClassDefSyntax cd, ClassInfo ci, FunctionDefSyntax fd)
        {
            FunctionInfo fi = ci.Methods["__init__"];
            _sb.Append("    ").Append(Escape(cd.Name)).Append('(').Append(ParamList(fi)).Append(')');

            var declared = new HashSet<string>(fi.Parameters.Select(p => p.Name)) { "self" };
            IReadOnlyList<StatementSyntax> bodyStatements = fd.Body?.Statements ?? Array.Empty<StatementSyntax>();

            // `super().__init__(args)` as the first statement becomes the C++ base-class
            // member-initializer — it MUST run there, not as an ordinary statement, or the
            // base subobject is constructed before we'd otherwise call its constructor.
            int skip = 0;
            if (bodyStatements.Count > 0 && IsSuperInitCall(bodyStatements[0], out CallExpression superCall))
            {
                _sb.Append(" : ").Append(ResolvedBaseCppName(ci.BaseClassName)).Append('(').Append(EmitArgList(superCall.Arguments)).Append(')');
                skip = 1;
            }

            _sb.Append(" {\n");
            EmitStatements(bodyStatements.Skip(skip), 2, declared);
            _sb.Append("    }\n");
        }

        private static bool IsSuperInitCall(StatementSyntax s, out CallExpression call)
        {
            call = null;
            if (!(s is ExpressionStatement es) || !(es.Expression is CallExpression ce)) return false;
            if (!(ce.Callee is AttributeExpression attr) || attr.Name != "__init__") return false;
            if (!(attr.Target is CallExpression superCall) || !(superCall.Callee is NameExpression sn) || sn.Name != "super" || superCall.Arguments.Count > 0) return false;
            call = ce;
            return true;
        }

        private void EmitMethod(ClassInfo ci, FunctionDefSyntax fd)
        {
            FunctionInfo fi = ci.Methods[fd.Name];
            _sb.Append("    ");
            if (fi.IsStatic) _sb.Append("static ");
            _sb.Append(TypeName(fi.ReturnType)).Append(' ').Append(Escape(fd.Name)).Append('(').Append(ParamList(fi)).Append(") {\n");
            var declared = new HashSet<string>(fi.Parameters.Select(p => p.Name));
            if (!fi.IsStatic) declared.Add("self");
            EmitStatements(fd.Body?.Statements, 2, declared);
            _sb.Append("    }\n");
        }

        // ================================================================
        // Module-level globals + entry point
        // ================================================================

        private void EmitGlobalVariable(AssignmentStatement asn)
        {
            if (asn.Targets.Count != 1 || !(asn.Targets[0] is NameExpression n)) return; // Pass 1 already restricted this shape
            CppType t = TypeOf(asn.Value);
            _sb.Append(TypeName(t)).Append(' ').Append(Escape(n.Name)).Append(" = ").Append(EmitExpr(asn.Value)).Append(";\n");
        }

        private void EmitEntryPoint(FunctionDefSyntax mainFd)
        {
            FunctionInfo fi = _checker.Functions["main"];
            bool returnsInt = fi.ReturnType.Equals(CppType.Int);
            _sb.Append("int main(int argc, char** argv) {\n");
            var declared = new HashSet<string>();
            if (returnsInt)
            {
                // main()'s own return value becomes the process exit code directly — the
                // closest honest analogue in a single-file program to Python's common
                // `sys.exit(main())` pattern.
                EmitStatements(mainFd.Body?.Statements, 1, declared, isMainReturningExitCode: true);
            }
            else
            {
                EmitStatements(mainFd.Body?.Statements, 1, declared);
                _sb.Append("    return 0;\n");
            }
            _sb.Append("}\n");
        }

        // ================================================================
        // Statements
        // ================================================================

        private static string Ind(int level) => new string(' ', level * 4);

        private void EmitStatements(IEnumerable<StatementSyntax> statements, int indent, HashSet<string> declared, bool isMainReturningExitCode = false)
        {
            if (statements == null) return;
            foreach (StatementSyntax s in statements) EmitStatement(s, indent, declared, isMainReturningExitCode);
        }

        private void EmitStatement(StatementSyntax s, int indent, HashSet<string> declared, bool isMainReturningExitCode = false)
        {
            switch (s)
            {
                case FunctionDefSyntax nestedFd: EmitNestedFunction(nestedFd, indent, declared); return;

                case AssignmentStatement asn: EmitAssignment(asn, indent, declared); return;

                case AugmentedAssignmentStatement aug:
                {
                    string target = EmitExpr(aug.Target);
                    string rhs = EmitBinaryOpValue(aug.Operator, aug.Target, aug.Value);
                    _sb.Append(Ind(indent)).Append(target).Append(" = ").Append(rhs).Append(";\n");
                    return;
                }

                case ExpressionStatement es:
                    if (IsSuperInitCall(es, out _)) return; // already emitted via the constructor initializer list
                    _sb.Append(Ind(indent)).Append(EmitExpr(es.Expression)).Append(";\n");
                    return;

                case PassStatement _: return;
                case BreakStatement _: _sb.Append(Ind(indent)).Append("break;\n"); return;
                case ContinueStatement _: _sb.Append(Ind(indent)).Append("continue;\n"); return;

                case ReturnStatement rs:
                    if (isMainReturningExitCode) _sb.Append(Ind(indent)).Append("return ").Append(rs.Value != null ? EmitExpr(rs.Value) : "0").Append(";\n");
                    else if (rs.Value != null) _sb.Append(Ind(indent)).Append("return ").Append(EmitExpr(rs.Value)).Append(";\n");
                    else _sb.Append(Ind(indent)).Append("return;\n");
                    return;

                case RaiseStatement raise: EmitRaise(raise, indent); return;

                case AssertStatement assertS:
                    _sb.Append(Ind(indent)).Append("if (!").Append(WrapTruthy(assertS.Test)).Append(") throw pyrt::PyAssertionError(")
                       .Append(assertS.Message != null ? EmitAsString(assertS.Message) : "\"\"").Append(");\n");
                    return;

                case DelStatement del: EmitDel(del, indent); return;

                case GlobalStatement _: case NonlocalStatement _: case ImportStatement _: case FromImportStatement _:
                    return; // no C++ equivalent needed — see class comment

                case IfStatement ifs: EmitIf(ifs, indent, declared, isMainReturningExitCode); return;
                case WhileStatement ws:
                    _sb.Append(Ind(indent)).Append("while (").Append(WrapTruthy(ws.Test)).Append(") {\n");
                    EmitStatements(ws.Body?.Statements, indent + 1, new HashSet<string>(declared), isMainReturningExitCode);
                    _sb.Append(Ind(indent)).Append("}\n");
                    return;
                case ForStatement fs: EmitFor(fs, indent, declared, isMainReturningExitCode); return;
                case TryStatement trys: EmitTry(trys, indent, declared, isMainReturningExitCode); return;

                default:
                    throw new NotSupportedException("PythonToCppEmitter: unsupported statement " + s.GetType().Name + " reached emission (Pass 1 should have rejected it)");
            }
        }

        private void EmitNestedFunction(FunctionDefSyntax fd, int indent, HashSet<string> declared)
        {
            // Pass 1 only accepts nested functions that don't capture via `nonlocal`, so a
            // plain (non-capturing) C++ lambda is an exact semantic match.
            FunctionInfo fi = _checker.Functions[fd.Name];
            _sb.Append(Ind(indent)).Append("auto ").Append(Escape(fd.Name)).Append(" = [](")
               .Append(ParamList(fi)).Append(") -> ").Append(TypeName(fi.ReturnType)).Append(" {\n");
            var innerDeclared = new HashSet<string>(fi.Parameters.Select(p => p.Name));
            EmitStatements(fd.Body?.Statements, indent + 1, innerDeclared);
            _sb.Append(Ind(indent)).Append("};\n");
            declared.Add(fd.Name);
        }

        private void EmitAssignment(AssignmentStatement asn, int indent, HashSet<string> declared)
        {
            if (asn.Targets.Count == 1 && asn.Targets[0] is NameExpression singleTarget)
            {
                CppType t = TypeOf(asn.Value);
                string rhs = EmitExpr(asn.Value);
                if (declared.Add(singleTarget.Name)) _sb.Append(Ind(indent)).Append(TypeName(t)).Append(' ').Append(Escape(singleTarget.Name)).Append(" = ").Append(rhs).Append(";\n");
                else _sb.Append(Ind(indent)).Append(Escape(singleTarget.Name)).Append(" = ").Append(rhs).Append(";\n");
                return;
            }

            if (asn.Targets.Count == 1 && asn.Targets[0] is TupleExpression tupleTarget)
            {
                string rhs = EmitExpr(asn.Value);
                bool anyNew = tupleTarget.Elements.Any(el => el is NameExpression n && !declared.Contains(n.Name));
                if (anyNew)
                {
                    _sb.Append(Ind(indent)).Append("auto [").Append(string.Join(", ", tupleTarget.Elements.Select(el => Escape(((NameExpression)el).Name)))).Append("] = ").Append(rhs).Append(";\n");
                    foreach (ExpressionSyntax el in tupleTarget.Elements) if (el is NameExpression n) declared.Add(n.Name);
                }
                else
                {
                    _sb.Append(Ind(indent)).Append("std::tie(").Append(string.Join(", ", tupleTarget.Elements.Select(el => Escape(((NameExpression)el).Name)))).Append(") = ").Append(rhs).Append(";\n");
                }
                return;
            }

            if (asn.Targets.Count == 1 && asn.Targets[0] is AttributeExpression attrTarget)
            {
                _sb.Append(Ind(indent)).Append(EmitExpr(attrTarget)).Append(" = ").Append(EmitExpr(asn.Value)).Append(";\n");
                return;
            }

            if (asn.Targets.Count == 1 && asn.Targets[0] is SubscriptExpression subTarget)
            {
                EmitSubscriptWrite(subTarget, asn.Value, indent);
                return;
            }

            if (asn.Targets.Count > 1)
            {
                CppType t = TypeOf(asn.Value);
                string tempName = "__pyrt_tmp" + (_tempCounter++);
                _sb.Append(Ind(indent)).Append(TypeName(t)).Append(' ').Append(tempName).Append(" = ").Append(EmitExpr(asn.Value)).Append(";\n");
                foreach (ExpressionSyntax target in asn.Targets)
                {
                    string name = ((NameExpression)target).Name;
                    if (declared.Add(name)) _sb.Append(Ind(indent)).Append(TypeName(t)).Append(' ').Append(Escape(name)).Append(" = ").Append(tempName).Append(";\n");
                    else _sb.Append(Ind(indent)).Append(Escape(name)).Append(" = ").Append(tempName).Append(";\n");
                }
            }
        }

        // `d[k] = v` needs `.set(k, v)` (dict) — a subscript WRITE is a different pyrt call
        // than a subscript READ (`.get(k)`), so it can't go through the general EmitExpr path.
        private void EmitSubscriptWrite(SubscriptExpression sub, ExpressionSyntax value, int indent)
        {
            CppType targetType = TypeOf(sub.Target);
            string targetText = EmitExpr(sub.Target);
            string valueText = EmitExpr(value);
            if (targetType is DictType)
            {
                _sb.Append(Ind(indent)).Append(targetText).Append(".set(").Append(EmitExpr(sub.Index)).Append(", ").Append(valueText).Append(");\n");
            }
            else if (targetType is ListType)
            {
                _sb.Append(Ind(indent)).Append(targetText).Append(".set_at(").Append(EmitExpr(sub.Index)).Append(", ").Append(valueText).Append(");\n");
            }
            else
            {
                throw new NotSupportedException("PythonToCppEmitter: subscript assignment on " + targetType + " reached emission");
            }
        }

        private void EmitRaise(RaiseStatement raise, int indent)
        {
            if (raise.Exception == null) { _sb.Append(Ind(indent)).Append("throw;\n"); return; }
            _sb.Append(Ind(indent)).Append("throw ").Append(EmitExpr(raise.Exception)).Append(";\n");
        }

        private void EmitDel(DelStatement del, int indent)
        {
            foreach (ExpressionSyntax target in del.Targets)
            {
                if (target is SubscriptExpression sub)
                {
                    CppType targetType = TypeOf(sub.Target);
                    if (targetType is DictType) _sb.Append(Ind(indent)).Append(EmitExpr(sub.Target)).Append(".erase(").Append(EmitExpr(sub.Index)).Append(");\n");
                    else if (targetType is ListType) _sb.Append(Ind(indent)).Append(EmitExpr(sub.Target)).Append(".pop_at(").Append(EmitExpr(sub.Index)).Append(");\n");
                }
                // `del name` (plain local) has no C++ equivalent — Python's static scoping in
                // this subset already means nothing observes the name becoming unbound.
            }
        }

        private void EmitIf(IfStatement ifs, int indent, HashSet<string> declared, bool isMainReturningExitCode)
        {
            _sb.Append(Ind(indent)).Append("if (").Append(WrapTruthy(ifs.Test)).Append(") {\n");
            EmitStatements(ifs.Body?.Statements, indent + 1, new HashSet<string>(declared), isMainReturningExitCode);
            _sb.Append(Ind(indent)).Append('}');
            foreach (IfStatement elif in ifs.Elifs)
            {
                _sb.Append(" else if (").Append(WrapTruthy(elif.Test)).Append(") {\n");
                EmitStatements(elif.Body?.Statements, indent + 1, new HashSet<string>(declared), isMainReturningExitCode);
                _sb.Append(Ind(indent)).Append('}');
            }
            if (ifs.Else != null)
            {
                _sb.Append(" else {\n");
                EmitStatements(ifs.Else.Statements, indent + 1, new HashSet<string>(declared), isMainReturningExitCode);
                _sb.Append(Ind(indent)).Append('}');
            }
            _sb.Append('\n');
        }

        private void EmitFor(ForStatement fs, int indent, HashSet<string> declared, bool isMainReturningExitCode)
        {
            var bodyDeclared = new HashSet<string>(declared);

            if (fs.Iter is CallExpression ce && ce.Callee is NameExpression cn && cn.Name == "range")
            {
                string varName = Escape(((NameExpression)fs.Target).Name);
                bodyDeclared.Add(((NameExpression)fs.Target).Name);
                string start = "0", stop, step = "1";
                var args = ce.Arguments.Select(a => EmitExpr(a.Value)).ToList();
                if (args.Count == 1) stop = args[0];
                else if (args.Count == 2) { start = args[0]; stop = args[1]; }
                else { start = args[0]; stop = args[1]; step = args[2]; }
                _sb.Append(Ind(indent)).Append("for (pyrt::py_int ").Append(varName).Append(" = ").Append(start).Append("; ")
                   .Append(varName).Append(step == "1" ? " < " : (step.StartsWith("-") ? " > " : " < ")).Append(stop).Append("; ")
                   .Append(varName).Append(" += ").Append(step).Append(") {\n");
                EmitStatements(fs.Body?.Statements, indent + 1, bodyDeclared, isMainReturningExitCode);
                _sb.Append(Ind(indent)).Append("}\n");
                return;
            }

            string iterExpr = EmitExpr(fs.Iter);
            if (fs.Target is NameExpression tn)
            {
                bodyDeclared.Add(tn.Name);
                _sb.Append(Ind(indent)).Append("for (const auto& ").Append(Escape(tn.Name)).Append(" : ").Append(iterExpr).Append(") {\n");
            }
            else if (fs.Target is TupleExpression tt)
            {
                foreach (ExpressionSyntax el in tt.Elements) if (el is NameExpression n) bodyDeclared.Add(n.Name);
                _sb.Append(Ind(indent)).Append("for (const auto& [").Append(string.Join(", ", tt.Elements.Select(el => Escape(((NameExpression)el).Name)))).Append("] : ").Append(iterExpr).Append(") {\n");
            }
            EmitStatements(fs.Body?.Statements, indent + 1, bodyDeclared, isMainReturningExitCode);
            _sb.Append(Ind(indent)).Append("}\n");
        }

        private void EmitTry(TryStatement trys, int indent, HashSet<string> declared, bool isMainReturningExitCode)
        {
            _sb.Append(Ind(indent)).Append("{\n");
            if (trys.Finally != null)
            {
                _sb.Append(Ind(indent + 1)).Append("pyrt::FinallyGuard __pyrt_finally([&]{\n");
                EmitStatements(trys.Finally.Statements, indent + 2, new HashSet<string>(declared), isMainReturningExitCode);
                _sb.Append(Ind(indent + 1)).Append("});\n");
            }
            _sb.Append(Ind(indent + 1)).Append("try {\n");
            var tryDeclared = new HashSet<string>(declared);
            EmitStatements(trys.Body?.Statements, indent + 2, tryDeclared, isMainReturningExitCode);
            if (trys.Else != null) EmitStatements(trys.Else.Statements, indent + 2, tryDeclared, isMainReturningExitCode);
            _sb.Append(Ind(indent + 1)).Append('}');

            foreach (ExceptHandler h in trys.Handlers)
            {
                string cppExType = h.ExceptionType != null ? ExceptionCppTypeName(h.ExceptionType) : null;
                if (cppExType == null) { _sb.Append(" catch (...) {\n"); }
                else
                {
                    string bindName = !string.IsNullOrEmpty(h.Name) ? Escape(h.Name) : "__pyrt_ex";
                    _sb.Append(" catch (").Append(cppExType).Append("& ").Append(bindName).Append(") {\n");
                }
                var handlerDeclared = new HashSet<string>(declared);
                EmitStatements(h.Body?.Statements, indent + 2, handlerDeclared, isMainReturningExitCode);
                _sb.Append(Ind(indent + 1)).Append('}');
            }
            _sb.Append('\n').Append(Ind(indent)).Append("}\n");
        }

        private string ExceptionCppTypeName(ExpressionSyntax exceptionType)
        {
            string name = ((NameExpression)exceptionType).Name;
            return BuiltinExceptionRuntimeNames.TryGetValue(name, out string mapped) ? mapped : Escape(name);
        }

        // ================================================================
        // Expressions
        // ================================================================

        private string WrapTruthy(ExpressionSyntax e) =>
            TypeOf(e).Equals(CppType.Bool) ? EmitExpr(e) : "pyrt::truthy(" + EmitExpr(e) + ")";

        private string EmitAsString(ExpressionSyntax e) =>
            TypeOf(e).Equals(CppType.Str) ? EmitExpr(e) : "pyrt::to_str(" + EmitExpr(e) + ")";

        private string EmitExpr(ExpressionSyntax e)
        {
            switch (e)
            {
                case null: return "";
                case NameExpression n: return n.Name == "self" ? "this" : Escape(n.Name); // Python's implicit receiver -> C++'s implicit receiver
                case ParenthesizedExpression pe: return "(" + EmitExpr(pe.Inner) + ")";
                case LiteralExpression lit: return EmitLiteral(lit);
                case BinaryExpression be: return EmitBinaryOpValue(be.Operator, be.Left, be.Right);
                case UnaryExpression ue: return EmitUnary(ue);
                case ComparisonExpression cmp: return EmitComparison(cmp);
                case ConditionalExpression ce: return "(" + WrapTruthy(ce.Condition) + " ? " + EmitExpr(ce.IfTrue) + " : " + EmitExpr(ce.IfFalse) + ")";
                case CallExpression call: return EmitCall(call);
                case SubscriptExpression sub: return EmitSubscriptRead(sub);
                case AttributeExpression attr: return EmitAttribute(attr);
                case TupleExpression tup: return "pyrt::Tuple<" + string.Join(", ", tup.Elements.Select(el => TypeName(TypeOf(el)))) + ">(" + string.Join(", ", tup.Elements.Select(EmitExpr)) + ")";
                case ListExpression list: return EmitListLiteral(list);
                case SetExpression set: return EmitSetLiteral(set);
                case DictExpression dict: return EmitDictLiteral(dict);
                case ComprehensionExpression comp: return EmitComprehension(comp);
                case FStringExpression fstr: return EmitFString(fstr);
                case StarredExpression star: return EmitExpr(star.Value); // only reached inside call-argument emission, which unpacks separately
                default:
                    throw new NotSupportedException("PythonToCppEmitter: unsupported expression " + e.GetType().Name + " reached emission (Pass 1 should have rejected it)");
            }
        }

        private string EmitLiteral(LiteralExpression lit)
        {
            Token t = lit.Token;
            switch (t.Kind)
            {
                case TokenKind.Number:
                    return NormalizeNumericLiteral(t.Text);
                case TokenKind.String:
                    return EmitStringLiteralAsPyrtStr(t.Text);
                case TokenKind.KwTrue: return "true";
                case TokenKind.KwFalse: return "false";
                case TokenKind.KwNone:
                    // Pass 1 cached the FULL Optional[T] context against this node (not just
                    // CppType.None) precisely so this decision can be made correctly: a
                    // shared_ptr-backed class type uses `nullptr`, everything else uses
                    // `std::optional`'s own empty-state spelling, `std::nullopt` — they are
                    // not interchangeable in C++.
                    return TypeOf(lit) is OptionalType ot && ot.Inner is ClassType ? "nullptr" : "std::nullopt";
                default: throw new NotSupportedException("PythonToCppEmitter: unsupported literal token kind " + t.Kind);
            }
        }

        // Python allows `_` digit separators (also valid in C++14+) and 0o/0b prefixes (NOT
        // valid in C++, which uses a bare leading 0 for octal and shares 0b for binary) — the
        // safest normalization is to parse the actual value and re-emit canonical decimal,
        // rather than trying to keep prefixes that only partially overlap between languages.
        private static string NormalizeNumericLiteral(string text)
        {
            string clean = text.Replace("_", "");
            bool isFloat = clean.IndexOf('.') >= 0 || clean.IndexOf('e') >= 0 || clean.IndexOf('E') >= 0;
            if (isFloat) return clean;
            if (clean.StartsWith("0o", StringComparison.OrdinalIgnoreCase))
                return Convert.ToInt64(clean.Substring(2), 8).ToString();
            if (clean.StartsWith("0b", StringComparison.OrdinalIgnoreCase))
                return Convert.ToInt64(clean.Substring(2), 2).ToString();
            return clean; // decimal and 0x-hex are already valid, identical C++ syntax
        }

        // Strips the Python literal's quotes/prefix and re-escapes only what's needed for a
        // double-quoted C++ literal (an embedded literal '"', and a literal newline character
        // inside a triple-quoted string) — existing backslash escape sequences (\n \t \\ \xHH
        // \uXXXX ...) are copied through unchanged since Python and C++ share that syntax.
        // For a REGULAR (non-f-string) literal — raw is the full token text, quotes/prefix
        // and all, and must be stripped before escaping.
        private static string EmitStringLiteralAsPyrtStr(string raw)
        {
            int i = 0;
            bool isRaw = false;
            while (i < raw.Length && char.IsLetter(raw[i])) { if (char.ToLowerInvariant(raw[i]) == 'r') isRaw = true; i++; }
            string body = raw.Substring(i);
            string inner;
            if (body.Length >= 6 && (body.StartsWith("\"\"\"", StringComparison.Ordinal) || body.StartsWith("'''", StringComparison.Ordinal)))
                inner = body.Substring(3, body.Length - 6);
            else if (body.Length >= 2) inner = body.Substring(1, body.Length - 2);
            else inner = "";
            return EscapeAndWrapAsPyrtStr(inner, isRaw);
        }

        // For an f-string LITERAL SEGMENT — RawFStringSegmentText already returns the raw,
        // UNQUOTED body text (no prefix/quotes to strip), so only escaping is needed. Calling
        // EmitStringLiteralAsPyrtStr on this instead (as an earlier version of this method
        // did) mis-parses ordinary leading letters as if they were a string prefix to skip,
        // silently dropping most of the literal text.
        private static string EmitFStringSegmentAsPyrtStr(string rawSegmentText) => EscapeAndWrapAsPyrtStr(rawSegmentText, isRaw: false);

        private static string EscapeAndWrapAsPyrtStr(string inner, bool isRaw)
        {
            var sb = new StringBuilder("pyrt::Str(\"");
            foreach (char c in inner)
            {
                if (isRaw && c == '\\') sb.Append("\\\\");
                else if (c == '"') sb.Append("\\\"");
                else if (c == '\n') sb.Append("\\n");
                else if (c == '\r') sb.Append("\\r");
                else sb.Append(c);
            }
            sb.Append("\")");
            return sb.ToString();
        }

        private string EmitArgList(IReadOnlyList<CallArgument> args) => string.Join(", ", args.Select(a => EmitExpr(a.Value)));

        private string EmitBinaryOpValue(BinaryOperator op, ExpressionSyntax leftExpr, ExpressionSyntax rightExpr)
        {
            string l = EmitExpr(leftExpr), r = EmitExpr(rightExpr);
            CppType lt = TypeOf(leftExpr), rt = TypeOf(rightExpr);
            bool bothInt = lt.Equals(CppType.Int) && rt.Equals(CppType.Int);
            bool anyFloat = lt.Equals(CppType.Float) || rt.Equals(CppType.Float);

            switch (op)
            {
                case BinaryOperator.Add:
                    if (bothInt) return "pyrt::checked_add(" + l + ", " + r + ")";
                    return "(" + l + " + " + r + ")"; // float/float, str+str (Str::operator+), List+List — all overload +
                case BinaryOperator.Subtract:
                    return bothInt ? "pyrt::checked_sub(" + l + ", " + r + ")" : "(" + l + " - " + r + ")";
                case BinaryOperator.Multiply:
                    if (bothInt) return "pyrt::checked_mul(" + l + ", " + r + ")";
                    if (lt.Equals(CppType.Str) && rt.Equals(CppType.Int)) return l + ".repeat(" + r + ")";
                    if (lt.Equals(CppType.Int) && rt.Equals(CppType.Str)) return r + ".repeat(" + l + ")";
                    return "(" + l + " * " + r + ")";
                case BinaryOperator.Divide:
                    return bothInt ? "pyrt::true_div(" + l + ", " + r + ")" : "(static_cast<pyrt::py_float>(" + l + ") / static_cast<pyrt::py_float>(" + r + "))";
                case BinaryOperator.FloorDivide:
                    return bothInt ? "pyrt::floordiv(" + l + ", " + r + ")" : "pyrt::floordiv_float(static_cast<pyrt::py_float>(" + l + "), static_cast<pyrt::py_float>(" + r + "))";
                case BinaryOperator.Modulo:
                    return bothInt ? "pyrt::mod(" + l + ", " + r + ")" : "pyrt::fmod_py(static_cast<pyrt::py_float>(" + l + "), static_cast<pyrt::py_float>(" + r + "))";
                case BinaryOperator.Power:
                    return bothInt ? "pyrt::pow_int(" + l + ", " + r + ")" : "pyrt::pow_float(static_cast<pyrt::py_float>(" + l + "), static_cast<pyrt::py_float>(" + r + "))";
                case BinaryOperator.BitAnd: return "(" + l + " & " + r + ")";
                case BinaryOperator.BitOr: return "(" + l + " | " + r + ")";
                case BinaryOperator.BitXor: return "(" + l + " ^ " + r + ")";
                case BinaryOperator.LShift: return "(" + l + " << " + r + ")";
                case BinaryOperator.RShift: return "(" + l + " >> " + r + ")";
                case BinaryOperator.And: return "pyrt::py_and(" + l + ", " + r + ")";
                case BinaryOperator.Or: return "pyrt::py_or(" + l + ", " + r + ")";
                default: throw new NotSupportedException("PythonToCppEmitter: unsupported binary operator " + op);
            }
        }

        private string EmitUnary(UnaryExpression ue)
        {
            string operand = EmitExpr(ue.Operand);
            switch (ue.Operator)
            {
                case UnaryOperator.Plus: return "(+" + operand + ")";
                case UnaryOperator.Minus: return "(-" + operand + ")";
                case UnaryOperator.BitNot: return "(~" + operand + ")";
                case UnaryOperator.Not: return "(!" + WrapTruthy(ue.Operand) + ")";
                default: throw new NotSupportedException("PythonToCppEmitter: unsupported unary operator " + ue.Operator);
            }
        }

        private string EmitComparison(ComparisonExpression cmp)
        {
            var parts = new List<string>();
            ExpressionSyntax left = cmp.Left;
            for (int i = 0; i < cmp.Operators.Count; i++)
            {
                ComparisonOperator op = cmp.Operators[i];
                ExpressionSyntax right = cmp.Comparators[i];

                if (op == ComparisonOperator.Is || op == ComparisonOperator.IsNot)
                {
                    string opt = EmitExpr(left);
                    CppType lt = TypeOf(left);
                    string check = lt is OptionalType ot && ot.Inner is ClassType
                        ? opt + (op == ComparisonOperator.Is ? " == nullptr" : " != nullptr")
                        : opt + (op == ComparisonOperator.Is ? ".has_value() == false" : ".has_value() == true");
                    parts.Add(check);
                    left = right;
                    continue;
                }

                string l = EmitExpr(left), r = EmitExpr(right);
                string cppOp;
                switch (op)
                {
                    case ComparisonOperator.Eq: cppOp = "=="; break;
                    case ComparisonOperator.NotEq: cppOp = "!="; break;
                    case ComparisonOperator.Less: cppOp = "<"; break;
                    case ComparisonOperator.LessEq: cppOp = "<="; break;
                    case ComparisonOperator.Greater: cppOp = ">"; break;
                    case ComparisonOperator.GreaterEq: cppOp = ">="; break;
                    case ComparisonOperator.In: parts.Add(r + ".contains(" + l + ")"); left = right; continue;
                    case ComparisonOperator.NotIn: parts.Add("!" + r + ".contains(" + l + ")"); left = right; continue;
                    default: throw new NotSupportedException("PythonToCppEmitter: unsupported comparison operator " + op);
                }
                parts.Add("(" + l + " " + cppOp + " " + r + ")");
                left = right;
            }
            return parts.Count == 1 ? parts[0] : "(" + string.Join(" && ", parts) + ")";
        }

        private string EmitSubscriptRead(SubscriptExpression sub)
        {
            CppType targetType = TypeOf(sub.Target);
            string target = EmitExpr(sub.Target);

            if (sub.Index is SliceExpression sl)
            {
                string start = sl.Lower != null ? "std::optional<pyrt::py_int>(" + EmitExpr(sl.Lower) + ")" : "std::nullopt";
                string stop = sl.Upper != null ? "std::optional<pyrt::py_int>(" + EmitExpr(sl.Upper) + ")" : "std::nullopt";
                string step = sl.Step != null ? "std::optional<pyrt::py_int>(" + EmitExpr(sl.Step) + ")" : "std::nullopt";
                return target + ".slice(" + start + ", " + stop + ", " + step + ")";
            }

            string index = EmitExpr(sub.Index);
            switch (targetType)
            {
                case DictType _: return target + ".get(" + index + ")";
                case ListType _: return target + ".at(" + index + ")";
                case PrimitiveType p when p.Name == "str": return target + ".at(" + index + ")";
                case TupleType _:
                    return "std::get<" + ((LiteralExpression)sub.Index).Token.Text + ">(" + target + ")";
                default: throw new NotSupportedException("PythonToCppEmitter: subscript read on " + targetType + " reached emission");
            }
        }

        private string EmitAttribute(AttributeExpression attr)
        {
            CppType objType = TypeOf(attr.Target);
            string target = EmitExpr(attr.Target);
            string arrow = target + "->" + Escape(attr.Name);

            // @property methods are read like fields in Python — emit an implicit call.
            if (objType is ClassType ct && LookupMethodChain(ct.Name, attr.Name, out FunctionInfo fi) && fi.IsProperty)
                return arrow + "()";
            return arrow;
        }

        private bool LookupMethodChain(string className, string methodName, out FunctionInfo method)
        {
            for (string current = className; current != null;)
            {
                if (!_checker.Classes.TryGetValue(current, out ClassInfo ci)) break;
                if (ci.Methods.TryGetValue(methodName, out method)) return true;
                current = ci.BaseClassName;
            }
            method = null;
            return false;
        }

        private string EmitListLiteral(ListExpression list)
        {
            CppType elemType = TypeOf(list); // ListType — element type is its .Element
            string elemTypeName = TypeName(((ListType)elemType).Element);
            return "pyrt::List<" + elemTypeName + ">({" + string.Join(", ", list.Elements.Select(EmitExpr)) + "})";
        }

        private string EmitSetLiteral(SetExpression set)
        {
            if (set.Elements.Count == 0) return "pyrt::Set<" + TypeName(((SetType)TypeOf(set)).Element) + ">()";
            string elemTypeName = TypeName(((SetType)TypeOf(set)).Element);
            var sb = new StringBuilder("[]{ pyrt::Set<" + elemTypeName + "> __s;");
            foreach (ExpressionSyntax el in set.Elements) sb.Append(" __s.add(").Append(EmitExpr(el)).Append(");");
            sb.Append(" return __s; }()");
            return sb.ToString();
        }

        private string EmitDictLiteral(DictExpression dict)
        {
            var dt = (DictType)TypeOf(dict);
            string keyType = TypeName(dt.Key), valType = TypeName(dt.Value);
            var sb = new StringBuilder("[]{ pyrt::Dict<" + keyType + ", " + valType + "> __d;");
            foreach (DictEntry entry in dict.Entries) sb.Append(" __d.set(").Append(EmitExpr(entry.Key)).Append(", ").Append(EmitExpr(entry.Value)).Append(");");
            sb.Append(" return __d; }()");
            return sb.ToString();
        }

        private string EmitComprehension(ComprehensionExpression comp)
        {
            CppType resultType = TypeOf(comp);
            var sb = new StringBuilder("[&]{ ").Append(TypeName(resultType)).Append(" __r;\n");
            EmitComprehensionClauses(comp, 0, sb);
            sb.Append(" return __r; }()");
            return sb.ToString();
        }

        private void EmitComprehensionClauses(ComprehensionExpression comp, int clauseIndex, StringBuilder sb)
        {
            if (clauseIndex >= comp.Clauses.Count)
            {
                if (comp.Kind == ComprehensionKind.Dict) sb.Append("__r.set(").Append(EmitExpr(comp.Element)).Append(", ").Append(EmitExpr(comp.ValueElement)).Append(");");
                else if (comp.Kind == ComprehensionKind.Set) sb.Append("__r.add(").Append(EmitExpr(comp.Element)).Append(");");
                else sb.Append("__r.append(").Append(EmitExpr(comp.Element)).Append(");");
                return;
            }
            ComprehensionClause clause = comp.Clauses[clauseIndex];
            sb.Append("for (const auto& ").Append(Escape(((NameExpression)clause.Target).Name)).Append(" : ").Append(EmitExpr(clause.Iter)).Append(") { ");
            foreach (ExpressionSyntax ifExpr in clause.Ifs) sb.Append("if (").Append(WrapTruthy(ifExpr)).Append(") { ");
            EmitComprehensionClauses(comp, clauseIndex + 1, sb);
            for (int i = 0; i < clause.Ifs.Count; i++) sb.Append(" }");
            sb.Append(" }\n");
        }

        private string EmitFString(FStringExpression fstr)
        {
            var sb = new StringBuilder("(");
            bool first = true;
            for (int i = 0; i < fstr.Parts.Count; i++)
            {
                if (!first) sb.Append(" + ");
                first = false;
                if (fstr.Parts[i] is LiteralExpression lit)
                {
                    sb.Append(EmitFStringSegmentAsPyrtStr(RawFStringSegmentText(lit)));
                }
                else if (fstr.Parts[i] is ExpressionSyntax expr)
                {
                    char? conv = i < fstr.Conversions.Count ? fstr.Conversions[i] : null;
                    string spec = i < fstr.FormatSpecs.Count ? fstr.FormatSpecs[i] : null;
                    string valueExpr = EmitExpr(expr);
                    if (conv == 'r') valueExpr = "pyrt::Str(pyrt::repr(" + valueExpr + "))";
                    if (!string.IsNullOrEmpty(spec))
                        sb.Append("pyrt::Str(pyrt::format(").Append(valueExpr).Append(", \"").Append(spec.Replace("\\", "\\\\").Replace("\"", "\\\"")).Append("\"))");
                    else
                        sb.Append("pyrt::Str(pyrt::to_str(").Append(valueExpr).Append("))");
                }
            }
            if (first) sb.Append("pyrt::Str(\"\")");
            sb.Append(')');
            return sb.ToString();
        }

        // Mirrors PythonPrettyPrinter.RawFStringSegmentText — see that method's comment for
        // why a plain TokenKind.String part (from implicit concatenation) needs unquoting
        // while an FStringMiddle part is already raw.
        private static string RawFStringSegmentText(LiteralExpression lit)
        {
            if (lit.Token == null) return "";
            if (lit.Token.Kind == TokenKind.FStringMiddle) return (lit.Token.Value as string) ?? lit.Token.Text;
            string raw = lit.Token.Text;
            int i = 0;
            while (i < raw.Length && char.IsLetter(raw[i])) i++;
            string body = raw.Substring(i);
            if (body.Length >= 6 && (body.StartsWith("\"\"\"", StringComparison.Ordinal) || body.StartsWith("'''", StringComparison.Ordinal)))
                return body.Substring(3, body.Length - 6);
            if (body.Length >= 2) return body.Substring(1, body.Length - 2);
            return body;
        }

        private string EmitCall(CallExpression call)
        {
            if (call.Callee is NameExpression calleeName)
            {
                string name = calleeName.Name;
                if (_checker.Classes.TryGetValue(name, out ClassInfo constructedClass))
                {
                    // Exception classes are thrown/caught by value (C++'s own idiom, and what
                    // pyrt's exception hierarchy is built for) — NOT wrapped in shared_ptr like
                    // every other class instance. See TypeName's matching special case.
                    return constructedClass.IsExceptionType
                        ? Escape(name) + "(" + EmitArgList(call.Arguments) + ")"
                        : "std::make_shared<" + Escape(name) + ">(" + EmitArgList(call.Arguments) + ")";
                }
                if (name == "print") return EmitPrintCall(call);
                if (name == "len") return EmitExpr(call.Arguments[0].Value) + ".len()";
                if (name == "str") return TypeOf(call.Arguments[0].Value).Equals(CppType.Str) ? EmitExpr(call.Arguments[0].Value) : "pyrt::Str(pyrt::to_str(" + EmitExpr(call.Arguments[0].Value) + "))";
                if (name == "int") return EmitIntConversion(call.Arguments[0].Value);
                if (name == "float") return "static_cast<pyrt::py_float>(" + EmitExpr(call.Arguments[0].Value) + ")";
                if (name == "bool") return WrapTruthy(call.Arguments[0].Value);
                if (name == "abs") return "std::abs(" + EmitExpr(call.Arguments[0].Value) + ")";
                if (name == "sorted") return EmitSortedCall(call);
                if (name == "min" || name == "max") return EmitMinMaxCall(call, name);
                if (name == "list") return EmitExpr(call.Arguments[0].Value); // pyrt::List already has value copy semantics via .copy() where needed; a bare list(x) on a List is an identity conversion in this subset
                if (name == "set") return EmitSetFromListCall(call);

                // free function / resolved lambda
                return Escape(name) + "(" + EmitArgList(call.Arguments) + ")";
            }

            if (call.Callee is AttributeExpression superAttr && superAttr.Name == "__init__" &&
                superAttr.Target is CallExpression superCall && superCall.Callee is NameExpression sn && sn.Name == "super")
            {
                // Handled at the constructor-initializer-list level; a bare occurrence here
                // (not as the constructor's first statement) shouldn't normally happen since
                // Pass 1 only accepts it in that position, but emit a same-shape call as a
                // defensive fallback rather than crashing.
                return "/* super().__init__ already applied via base-class initializer */ (void)0";
            }

            if (call.Callee is AttributeExpression methodAttr)
            {
                // Static/classmethod called via the class name directly (Box.unit()) — Pass 1
                // never called InferExpr on a bare class-name NameExpression in this shape (it
                // isn't a variable), so NodeTypes has no entry for it; TypeOf would throw.
                // Checked first and by the same signal Pass 1 used to decide this shape:
                // absence of a cached type on a name that IS a known class.
                if (methodAttr.Target is NameExpression classNameRef && !_checker.NodeTypes.ContainsKey(methodAttr.Target) &&
                    _checker.Classes.ContainsKey(classNameRef.Name))
                {
                    return Escape(classNameRef.Name) + "::" + Escape(methodAttr.Name) + "(" + EmitArgList(call.Arguments) + ")";
                }

                CppType objType = TypeOf(methodAttr.Target);
                string target = EmitExpr(methodAttr.Target);
                if (objType is ListType || objType is DictType || objType is SetType)
                    return EmitCollectionMethodCall(target, objType, methodAttr.Name, call.Arguments);
                if (objType is ClassType ct)
                {
                    LookupMethodChain(ct.Name, methodAttr.Name, out FunctionInfo fi);
                    if (fi != null && fi.IsStatic) return Escape(ct.Name) + "::" + Escape(methodAttr.Name) + "(" + EmitArgList(call.Arguments) + ")";
                    return target + "->" + Escape(methodAttr.Name) + "(" + EmitArgList(call.Arguments) + ")";
                }
            }

            throw new NotSupportedException("PythonToCppEmitter: unsupported call target reached emission");
        }

        private string EmitPrintCall(CallExpression call)
        {
            if (call.Arguments.Count == 0) return "pyrt::print()";
            if (call.Arguments.Count == 1) return "pyrt::print(" + EmitExpr(call.Arguments[0].Value) + ")";
            // print(a, b, c) — Python joins with a space; build the joined Str then print it.
            var parts = call.Arguments.Select(a => EmitAsString(a.Value));
            return "pyrt::print(" + string.Join(" + pyrt::Str(\" \") + ", parts) + ")";
        }

        private string EmitIntConversion(ExpressionSyntax arg)
        {
            CppType t = TypeOf(arg);
            if (t.Equals(CppType.Int)) return EmitExpr(arg);
            if (t.Equals(CppType.Float)) return "static_cast<pyrt::py_int>(" + EmitExpr(arg) + ")";
            if (t.Equals(CppType.Bool)) return "static_cast<pyrt::py_int>(" + EmitExpr(arg) + ")";
            if (t.Equals(CppType.Str)) return "std::stoll(" + EmitExpr(arg) + ".bytes())";
            throw new NotSupportedException("PythonToCppEmitter: int(...) on " + t + " reached emission");
        }

        private string EmitSortedCall(CallExpression call)
        {
            string src = EmitExpr(call.Arguments[0].Value);
            CppType argType = TypeOf(call.Arguments[0].Value);
            CppType elemType = argType is ListType lt ? lt.Element : ((SetType)argType).Element;
            string tn = TypeName(elemType);
            return "[&]{ std::vector<" + tn + "> __v(" + src + ".begin(), " + src + ".end()); std::sort(__v.begin(), __v.end()); return pyrt::List<" + tn + ">(std::move(__v)); }()";
        }

        private string EmitMinMaxCall(CallExpression call, string name)
        {
            string cmp = name == "min" ? "<" : ">";
            if (call.Arguments.Count == 1)
            {
                string src = EmitExpr(call.Arguments[0].Value);
                return "*std::" + name + "_element(" + src + ".begin(), " + src + ".end())";
            }
            // 2+ positional args
            string acc = EmitExpr(call.Arguments[0].Value);
            for (int i = 1; i < call.Arguments.Count; i++)
            {
                string next = EmitExpr(call.Arguments[i].Value);
                acc = "(" + acc + " " + cmp + " " + next + " ? " + acc + " : " + next + ")";
            }
            return acc;
        }

        private string EmitSetFromListCall(CallExpression call)
        {
            string src = EmitExpr(call.Arguments[0].Value);
            var lt = (ListType)TypeOf(call.Arguments[0].Value);
            string tn = TypeName(lt.Element);
            return "[&]{ pyrt::Set<" + tn + "> __s; for (const auto& __e : " + src + ") __s.add(__e); return __s; }()";
        }

        // Every Python collection method name here already matches pyrt.hpp's own method
        // name — the one exception is `set.union()`, renamed to `union_with` in the runtime
        // because `union` is a C++ keyword (can't be a member function name).
        private string EmitCollectionMethodCall(string target, CppType objType, string methodName, IReadOnlyList<CallArgument> args)
        {
            string cppMethod = (objType is SetType && methodName == "union") ? "union_with" : methodName;
            return target + "." + cppMethod + "(" + EmitArgList(args) + ")";
        }
    }
