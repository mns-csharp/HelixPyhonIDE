namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using System.Collections.Generic;
    using System.Text;
    using HelixPythonNamespace.GuiDesigner.Model;
    using K = HelixPythonNamespace.GuiDesigner.Model.GuiControlKind;
    using EC = HelixPythonNamespace.GuiDesigner.Emit.EmitterCommon;

    /// <summary>Generates a wxPython module from a GuiForm. Port of the C++ <c>WxPythonEmitter</c>.</summary>
    public sealed class WxPythonEmitter : IGuiCodeEmitter
    {
        public string FrameworkName { get { return "WxPython"; } }
        public string SourceExtension { get { return ".py"; } }
        public string AutoGeneratedMarker { get { return "# AUTO-GENERATED by HelixPython."; } }

        private static bool IsNonVisual(K kind)
        {
            switch (kind)
            {
                case K.Timer:
                case K.FileSystemWatcher:
                case K.Process:
                case K.NotifyIcon:
                case K.ToolTip:
                case K.ImageList:
                case K.BackgroundWorker:
                case K.ErrorProvider:
                case K.HelpProvider:
                case K.SerialPort:
                case K.BindingSource:
                case K.DataSet:
                case K.PrintDocument:
                case K.PageSetupDialog:
                case K.PrintDialog:
                case K.PrintPreviewDialog:
                case K.ColorDialog:
                case K.FolderBrowserDialog:
                case K.FontDialog:
                case K.OpenFileDialog:
                case K.SaveFileDialog:
                    return true;
                default: return false;
            }
        }

        private static void CollectImports(GuiForm form, out bool needsAdv, out bool needsRichtext)
        {
            needsAdv = false; needsRichtext = false;
            foreach (GuiControl c in form.Controls)
            {
                switch (c.Kind)
                {
                    case K.LinkLabel:
                    case K.DateTimePicker:
                    case K.MonthCalendar:
                    case K.NotifyIcon: needsAdv = true; break;
                    case K.RichTextBox: needsRichtext = true; break;
                    default: break;
                }
            }
        }

        private static string EvtFor(K kind, string eventName)
        {
            if (eventName == "Click" || eventName == "command")
            {
                if (kind == K.CheckBox) return "wx.EVT_CHECKBOX";
                if (kind == K.RadioButton) return "wx.EVT_RADIOBUTTON";
                return "wx.EVT_BUTTON";
            }
            if (eventName == "TextChanged") return "wx.EVT_TEXT";
            if (eventName == "CheckedChanged" || eventName == "CheckStateChanged") return "wx.EVT_CHECKBOX";
            if (eventName == "ValueChanged")
            {
                if (kind == K.TrackBar) return "wx.EVT_SLIDER";
                return "wx.EVT_SPINCTRL";
            }
            if (eventName == "SelectedIndexChanged" || eventName == "SelectionChanged")
            {
                if (kind == K.ListBox || kind == K.CheckedListBox) return "wx.EVT_LISTBOX";
                return "wx.EVT_COMBOBOX";
            }
            if (eventName == "Tick") return "wx.EVT_TIMER";
            if (eventName == "MouseDown" || eventName == "Click") return "wx.EVT_LEFT_DOWN";
            if (eventName == "MouseUp") return "wx.EVT_LEFT_UP";
            if (eventName == "MouseMove") return "wx.EVT_MOTION";
            if (eventName == "DoubleClick" || eventName == "ItemActivate") return "wx.EVT_LEFT_DCLICK";
            if (eventName == "KeyDown") return "wx.EVT_KEY_DOWN";
            if (eventName == "KeyUp") return "wx.EVT_KEY_UP";
            if (eventName == "GotFocus") return "wx.EVT_SET_FOCUS";
            if (eventName == "LostFocus") return "wx.EVT_KILL_FOCUS";
            if (eventName == "Resize") return "wx.EVT_SIZE";
            if (eventName == "Paint") return "wx.EVT_PAINT";
            return "";
        }

        private static string ChoicesList(List<string> items)
        {
            StringBuilder ss = new StringBuilder("[");
            bool first = true;
            foreach (string it in items)
            {
                if (!first) ss.Append(", ");
                ss.Append("'").Append(EC.PyEscape(it)).Append("'");
                first = false;
            }
            ss.Append("]");
            return ss.ToString();
        }

        private static void EmitBuild(StringBuilder o, GuiControl c)
        {
            string self = "self." + EC.SafeMember(c.Name);
            string text = EC.PropOr(c, "Text", c.Name);
            string esc = EC.PyEscape(text);
            string pos = "(" + c.X + ", " + c.Y + ")";
            string size = "(" + c.Width + ", " + c.Height + ")";

            switch (c.Kind)
            {
                case K.Form: return;
                case K.Button:
                    o.Append("        ").Append(self).Append(" = wx.Button(self, label='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.Label:
                    o.Append("        ").Append(self).Append(" = wx.StaticText(self, label='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.LinkLabel:
                    o.Append("        ").Append(self).Append(" = wx.adv.HyperlinkCtrl(self, label='").Append(esc).Append("', url='', pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.TextBox:
                {
                    bool multi = EC.PropOr(c, "Multiline") == "True" || EC.PropOr(c, "Multiline") == "true";
                    o.Append("        ").Append(self).Append(" = wx.TextCtrl(self, value='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size);
                    if (multi) o.Append(", style=wx.TE_MULTILINE");
                    o.Append(")\n");
                    break;
                }
                case K.MaskedTextBox:
                    o.Append("        # TODO: MaskedTextBox — wx.lib.masked.TextCtrl is the closest match. Plain wx.TextCtrl placeholder.\n");
                    o.Append("        ").Append(self).Append(" = wx.TextCtrl(self, value='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.RichTextBox:
                    o.Append("        ").Append(self).Append(" = wx.richtext.RichTextCtrl(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    if (text.Length > 0) o.Append("        ").Append(self).Append(".SetValue('").Append(esc).Append("')\n");
                    break;
                case K.CheckBox:
                {
                    o.Append("        ").Append(self).Append(" = wx.CheckBox(self, label='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    string ch = EC.PropOr(c, "Checked");
                    if (ch == "True" || ch == "true") o.Append("        ").Append(self).Append(".SetValue(True)\n");
                    break;
                }
                case K.RadioButton:
                {
                    o.Append("        ").Append(self).Append(" = wx.RadioButton(self, label='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    string ch = EC.PropOr(c, "Checked");
                    if (ch == "True" || ch == "true") o.Append("        ").Append(self).Append(".SetValue(True)\n");
                    break;
                }
                case K.ComboBox:
                    o.Append("        ").Append(self).Append(" = wx.ComboBox(self, value='").Append(esc).Append("', choices=").Append(ChoicesList(EC.SplitCsv(EC.PropOr(c, "Items")))).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.DomainUpDown:
                    o.Append("        ").Append(self).Append(" = wx.ComboBox(self, value='").Append(esc).Append("', choices=").Append(ChoicesList(EC.SplitCsv(EC.PropOr(c, "Items")))).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(", style=wx.CB_READONLY)\n"); break;
                case K.ListBox:
                    o.Append("        ").Append(self).Append(" = wx.ListBox(self, choices=").Append(ChoicesList(EC.SplitCsv(EC.PropOr(c, "Items")))).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.CheckedListBox:
                    o.Append("        ").Append(self).Append(" = wx.CheckListBox(self, choices=").Append(ChoicesList(EC.SplitCsv(EC.PropOr(c, "Items")))).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.ListView:
                    o.Append("        ").Append(self).Append(" = wx.ListCtrl(self, pos=").Append(pos).Append(", size=").Append(size).Append(", style=wx.LC_REPORT)\n"); break;
                case K.TreeView:
                    o.Append("        ").Append(self).Append(" = wx.TreeCtrl(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.ProgressBar:
                    o.Append("        ").Append(self).Append(" = wx.Gauge(self, range=").Append(EC.IntPropOr(c, "Maximum", 100)).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    o.Append("        ").Append(self).Append(".SetValue(").Append(EC.IntPropOr(c, "Value", 0)).Append(")\n"); break;
                case K.TrackBar:
                    o.Append("        ").Append(self).Append(" = wx.Slider(self, value=").Append(EC.IntPropOr(c, "Value", 0)).Append(", minValue=").Append(EC.IntPropOr(c, "Minimum", 0)).Append(", maxValue=").Append(EC.IntPropOr(c, "Maximum", 10)).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.NumericUpDown:
                {
                    int v = EC.IntPropOr(c, "Value", 0);
                    o.Append("        ").Append(self).Append(" = wx.SpinCtrl(self, value='").Append(v).Append("', min=").Append(EC.IntPropOr(c, "Minimum", 0)).Append(", max=").Append(EC.IntPropOr(c, "Maximum", 100)).Append(", initial=").Append(v).Append(", pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                }
                case K.DateTimePicker:
                    o.Append("        ").Append(self).Append(" = wx.adv.DatePickerCtrl(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.MonthCalendar:
                    o.Append("        ").Append(self).Append(" = wx.adv.CalendarCtrl(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.GroupBox:
                    o.Append("        ").Append(self).Append(" = wx.StaticBox(self, label='").Append(esc).Append("', pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.Panel:
                case K.FlowLayoutPanel:
                case K.ToolStripContainer:
                    o.Append("        ").Append(self).Append(" = wx.Panel(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.TabControl:
                {
                    o.Append("        ").Append(self).Append(" = wx.Notebook(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    List<string> pages = EC.SplitCsv(EC.PropOr(c, "TabPages"));
                    if (pages.Count == 0) pages.Add("Page1");
                    foreach (string p in pages) o.Append("        ").Append(self).Append(".AddPage(wx.Panel(").Append(self).Append("), '").Append(EC.PyEscape(p)).Append("')\n");
                    break;
                }
                case K.SplitContainer:
                {
                    bool horizontal = EC.PropOr(c, "Orientation") == "Horizontal";
                    o.Append("        ").Append(self).Append(" = wx.SplitterWindow(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    o.Append("        # TODO: call ").Append(self).Append(".Split").Append(horizontal ? "Horizontally" : "Vertically").Append("(panel1, panel2) once child panels exist.\n");
                    break;
                }
                case K.TableLayoutPanel:
                    o.Append("        # TODO: TableLayoutPanel — wx uses wx.GridBagSizer; placeholder Panel for now.\n");
                    o.Append("        ").Append(self).Append(" = wx.Panel(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.MenuStrip:
                    o.Append("        ").Append(self).Append(" = wx.MenuBar()\n");
                    o.Append("        self.SetMenuBar(").Append(self).Append(")\n"); break;
                case K.StatusStrip:
                    o.Append("        ").Append(self).Append(" = self.CreateStatusBar()\n"); break;
                case K.ToolStrip:
                case K.BindingNavigator:
                    o.Append("        ").Append(self).Append(" = self.CreateToolBar()\n"); break;
                case K.ContextMenuStrip:
                    o.Append("        ").Append(self).Append(" = wx.Menu()\n");
                    o.Append("        # TODO: bind wx.EVT_CONTEXT_MENU to PopupMenu(").Append(self).Append(").\n"); break;
                case K.PictureBox:
                {
                    string img = EC.PropOr(c, "Image");
                    o.Append("        ").Append(self).Append(" = wx.StaticBitmap(self, ");
                    if (img.Length > 0) o.Append("bitmap=wx.Bitmap('").Append(EC.PyEscape(img)).Append("'), ");
                    o.Append("pos=").Append(pos).Append(", size=").Append(size).Append(")\n");
                    break;
                }
                case K.WebBrowser:
                    o.Append("        # TODO: WebBrowser — install wx.html2; use wx.html2.WebView.New(self).\n");
                    o.Append("        ").Append(self).Append(" = wx.Panel(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.DataGridView:
                    o.Append("        # TODO: DataGridView placeholder — use wx.grid.Grid for an editable grid.\n");
                    o.Append("        ").Append(self).Append(" = wx.ListCtrl(self, pos=").Append(pos).Append(", size=").Append(size).Append(", style=wx.LC_REPORT)\n"); break;
                case K.Chart:
                    o.Append("        # TODO: Chart placeholder — consider matplotlib wxAgg backend.\n");
                    o.Append("        ").Append(self).Append(" = wx.Panel(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.PrintPreviewControl:
                    o.Append("        # TODO: PrintPreviewControl — use wx.PrintPreview/PreviewFrame.\n");
                    o.Append("        ").Append(self).Append(" = wx.Panel(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
                case K.Timer:
                {
                    o.Append("        ").Append(self).Append(" = wx.Timer(self)\n");
                    string en = EC.PropOr(c, "Enabled");
                    if (en == "True" || en == "true") o.Append("        ").Append(self).Append(".Start(").Append(EC.IntPropOr(c, "Interval", 1000)).Append(")\n");
                    break;
                }
                case K.Process:
                    o.Append("        ").Append(self).Append(" = wx.Process(self)\n"); break;
                case K.NotifyIcon:
                    o.Append("        ").Append(self).Append(" = wx.adv.TaskBarIcon()\n"); break;
                case K.ToolTip:
                    return;
                case K.ImageList:
                    o.Append("        ").Append(self).Append(" = wx.ImageList(16, 16)\n"); break;
                case K.FileSystemWatcher:
                    o.Append("        # TODO: FileSystemWatcher — wx has no direct equivalent; consider watchdog.\n");
                    o.Append("        ").Append(self).Append(" = None\n"); break;
                case K.BackgroundWorker:
                    o.Append("        # TODO: BackgroundWorker — use threading.Thread with wx.CallAfter.\n");
                    o.Append("        ").Append(self).Append(" = None\n"); break;
                case K.ColorDialog:
                case K.FolderBrowserDialog:
                case K.FontDialog:
                case K.OpenFileDialog:
                case K.SaveFileDialog:
                    o.Append("        # ").Append(GuiControlKinds.ToToken(c.Kind)).Append(" is invoked via self.show_").Append(EC.SafeMember(c.Name)).Append("()\n");
                    return;
                case K.ErrorProvider:
                case K.HelpProvider:
                case K.SerialPort:
                case K.BindingSource:
                case K.DataSet:
                case K.PrintDocument:
                case K.PageSetupDialog:
                case K.PrintDialog:
                case K.PrintPreviewDialog:
                    o.Append("        # TODO: ").Append(GuiControlKinds.ToToken(c.Kind)).Append(" — no direct wx equivalent; resolve in user code.\n");
                    o.Append("        ").Append(self).Append(" = None\n"); break;
                default:
                    o.Append("        # TODO: Unsupported control kind ").Append(GuiControlKinds.ToToken(c.Kind)).Append("\n");
                    o.Append("        ").Append(self).Append(" = wx.Panel(self, pos=").Append(pos).Append(", size=").Append(size).Append(")\n"); break;
            }

            if (!IsNonVisual(c.Kind))
            {
                string en = EC.PropOr(c, "Enabled");
                if (en == "False" || en == "false") o.Append("        ").Append(self).Append(".Enable(False)\n");
                string vis = EC.PropOr(c, "Visible");
                if (vis == "False" || vis == "false") o.Append("        ").Append(self).Append(".Show(False)\n");
                string tt = EC.PropOr(c, "ToolTip");
                if (tt.Length > 0) o.Append("        ").Append(self).Append(".SetToolTip('").Append(EC.PyEscape(tt)).Append("')\n");
                string accName = EC.PropOr(c, "AccessibleName");
                string accDesc = EC.PropOr(c, "AccessibleDescription");
                if (accName.Length > 0) o.Append("        ").Append(self).Append(".SetName('").Append(EC.PyEscape(accName)).Append("')\n");
                if (accDesc.Length > 0) o.Append("        ").Append(self).Append(".SetHelpText('").Append(EC.PyEscape(accDesc)).Append("')\n");
                string fg = EC.PropOr(c, "ForeColor");
                string bg = EC.PropOr(c, "BackColor");
                if (fg.Length > 0) o.Append("        ").Append(self).Append(".SetForegroundColour('").Append(EC.PyEscape(fg)).Append("')\n");
                if (bg.Length > 0) o.Append("        ").Append(self).Append(".SetBackgroundColour('").Append(EC.PyEscape(bg)).Append("')\n");
            }
        }

        public string Emit(GuiForm form, string existingSource)
        {
            Dictionary<string, string> regions = CodeRegionPreserver.Parse(existingSource);
            bool needsAdv, needsRichtext;
            CollectImports(form, out needsAdv, out needsRichtext);

            StringBuilder o = new StringBuilder();
            o.Append(EC.AutoGenBanner());
            o.Append("import wx\n");
            if (needsAdv) o.Append("import wx.adv\n");
            if (needsRichtext) o.Append("import wx.richtext\n");
            o.Append("\n\n");
            o.Append("class ").Append(form.FormClassName).Append("(wx.Frame):\n");
            o.Append("    def __init__(self, parent=None):\n");
            o.Append("        super().__init__(parent, title='").Append(EC.PyEscape(form.Title)).Append("', size=(").Append(form.Width).Append(", ").Append(form.Height).Append("))\n");
            o.Append("        self._build_ui()\n");
            o.Append("        self._wire_events()\n");
            o.Append("        self.Show()\n");
            o.Append("\n");

            o.Append("    def _build_ui(self):\n");
            bool emittedAny = false;
            foreach (GuiControl c in form.Controls)
            {
                if (c.Kind == K.Form) continue;
                EmitBuild(o, c);
                emittedAny = true;
            }
            if (!emittedAny) o.Append("        pass\n");
            o.Append("\n");

            o.Append("    def _wire_events(self):\n");
            bool anyWired = false;
            foreach (GuiControl c in form.Controls)
            {
                if (c.Kind == K.Form || c.Kind == K.ToolTip) continue;
                string member = "self." + EC.SafeMember(c.Name);
                foreach (GuiEvent e in c.Events)
                {
                    if (string.IsNullOrEmpty(e.HandlerName)) continue;
                    string evt = EvtFor(c.Kind, e.EventName);
                    if (evt.Length == 0)
                        o.Append("        # TODO: '").Append(e.EventName).Append("' has no direct wx.EVT_* mapping for ").Append(GuiControlKinds.ToToken(c.Kind)).Append("; route to self.").Append(e.HandlerName).Append(" manually.\n");
                    else
                        o.Append("        self.Bind(").Append(evt).Append(", self.").Append(e.HandlerName).Append(", source=").Append(member).Append(")\n");
                    anyWired = true;
                }
            }
            if (!anyWired) o.Append("        pass\n");
            o.Append("\n");

            foreach (GuiControl c in form.Controls)
            {
                string member = EC.SafeMember(c.Name);
                string title = EC.PropOr(c, "Title", c.Name);
                string filter = EC.PropOr(c, "Filter", "All files (*.*)|*.*");
                switch (c.Kind)
                {
                    case K.OpenFileDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        with wx.FileDialog(self, '").Append(EC.PyEscape(title)).Append("', wildcard='").Append(EC.PyEscape(filter)).Append("', style=wx.FD_OPEN | wx.FD_FILE_MUST_EXIST) as dlg:\n");
                        o.Append("            return dlg.GetPath() if dlg.ShowModal() == wx.ID_OK else None\n\n");
                        break;
                    case K.SaveFileDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        with wx.FileDialog(self, '").Append(EC.PyEscape(title)).Append("', wildcard='").Append(EC.PyEscape(filter)).Append("', style=wx.FD_SAVE | wx.FD_OVERWRITE_PROMPT) as dlg:\n");
                        o.Append("            return dlg.GetPath() if dlg.ShowModal() == wx.ID_OK else None\n\n");
                        break;
                    case K.FolderBrowserDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        with wx.DirDialog(self, '").Append(EC.PyEscape(title)).Append("') as dlg:\n");
                        o.Append("            return dlg.GetPath() if dlg.ShowModal() == wx.ID_OK else None\n\n");
                        break;
                    case K.FontDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        data = wx.FontData()\n");
                        o.Append("        with wx.FontDialog(self, data) as dlg:\n");
                        o.Append("            return dlg.GetFontData().GetChosenFont() if dlg.ShowModal() == wx.ID_OK else None\n\n");
                        break;
                    case K.ColorDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        with wx.ColourDialog(self) as dlg:\n");
                        o.Append("            return dlg.GetColourData().GetColour() if dlg.ShowModal() == wx.ID_OK else None\n\n");
                        break;
                    default: break;
                }
            }

            {
                string regionName = "UserCode-handlers";
                StringBuilder defaultBody = new StringBuilder();
                HashSet<string> emitted = new HashSet<string>(System.StringComparer.Ordinal);
                foreach (GuiControl c in form.Controls)
                    foreach (GuiEvent e in c.Events)
                    {
                        if (string.IsNullOrEmpty(e.HandlerName)) continue;
                        if (!emitted.Add(e.HandlerName)) continue;
                        defaultBody.Append("def ").Append(e.HandlerName).Append("(*args, **kwargs):\n    pass\n\n");
                    }
                if (defaultBody.Length == 0) defaultBody.Append("# Add custom handlers here.\n");
                o.Append("# region ").Append(regionName).Append("\n");
                o.Append(CodeRegionPreserver.GetOrDefault(regions, regionName, defaultBody.ToString()));
                o.Append("# endregion\n\n");
            }

            {
                string regionName = "UserCode-main";
                string defaultBody =
                    "if __name__ == '__main__':\n" +
                    "    app = wx.App(False)\n" +
                    "    frame = " + form.FormClassName + "()\n" +
                    "    app.MainLoop()\n";
                o.Append("# region ").Append(regionName).Append("\n");
                o.Append(CodeRegionPreserver.GetOrDefault(regions, regionName, defaultBody));
                o.Append("# endregion\n");
            }

            return o.ToString();
        }
    }
