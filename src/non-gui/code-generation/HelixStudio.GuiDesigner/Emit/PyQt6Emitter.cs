namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using System.Collections.Generic;
    using System.Text;
    using HelixPythonNamespace.GuiDesigner.Model;
    using K = HelixPythonNamespace.GuiDesigner.Model.GuiControlKind;
    using EC = HelixPythonNamespace.GuiDesigner.Emit.EmitterCommon;

    /// <summary>
    /// Generates a PyQt6 module from a GuiForm (QWidget, absolute setGeometry placement,
    /// signal/slot wiring). Port of the C++ <c>PyQt6Emitter</c>. <see cref="PySide6Emitter"/>
    /// subclasses this and only swaps the import prefix.
    /// </summary>
    public class PyQt6Emitter : IGuiCodeEmitter
    {
        public virtual string FrameworkName { get { return "PyQt6"; } }
        public string SourceExtension { get { return ".py"; } }
        public string AutoGeneratedMarker { get { return "# AUTO-GENERATED by HelixPython."; } }
        protected virtual string ImportPrefix { get { return "PyQt6"; } }

        private sealed class UsedSymbols
        {
            public SortedSet<string> Widgets = new SortedSet<string>(System.StringComparer.Ordinal);
            public SortedSet<string> Gui = new SortedSet<string>(System.StringComparer.Ordinal);
            public SortedSet<string> Core = new SortedSet<string>(System.StringComparer.Ordinal);
            public bool NeedsQt;
        }

        private static void CollectKindSymbols(GuiControl c, UsedSymbols used)
        {
            K kind = c.Kind;
            switch (kind)
            {
                case K.Form: used.Widgets.Add("QWidget"); break;
                case K.Button: used.Widgets.Add("QPushButton"); break;
                case K.Label: used.Widgets.Add("QLabel"); break;
                case K.LinkLabel: used.Widgets.Add("QLabel"); break;
                case K.TextBox:
                    // Import only the widget actually emitted (see the K.TextBox emission
                    // below): QPlainTextEdit for Multiline, else QLineEdit. Importing both
                    // left one unused (PY5001) in generated single-line-textbox forms.
                    {
                        bool multi = EC.PropOr(c, "Multiline") == "True" || EC.PropOr(c, "Multiline") == "true";
                        used.Widgets.Add(multi ? "QPlainTextEdit" : "QLineEdit");
                        break;
                    }
                case K.MaskedTextBox: used.Widgets.Add("QLineEdit"); break;
                case K.RichTextBox: used.Widgets.Add("QTextEdit"); break;
                case K.CheckBox: used.Widgets.Add("QCheckBox"); break;
                case K.RadioButton: used.Widgets.Add("QRadioButton"); break;
                case K.ComboBox:
                case K.DomainUpDown: used.Widgets.Add("QComboBox"); break;
                case K.ListBox:
                case K.CheckedListBox: used.Widgets.Add("QListWidget"); used.Widgets.Add("QListWidgetItem"); used.NeedsQt = true; break;
                case K.ListView:
                case K.TreeView:
                case K.DataGridView: used.Widgets.Add("QTreeWidget"); used.Widgets.Add("QTreeWidgetItem"); break;
                case K.ProgressBar: used.Widgets.Add("QProgressBar"); break;
                case K.TrackBar: used.Widgets.Add("QSlider"); used.NeedsQt = true; break;
                case K.NumericUpDown: used.Widgets.Add("QSpinBox"); break;
                case K.DateTimePicker: used.Widgets.Add("QDateTimeEdit"); break;
                case K.MonthCalendar: used.Widgets.Add("QCalendarWidget"); break;
                case K.GroupBox: used.Widgets.Add("QGroupBox"); break;
                case K.Panel:
                case K.FlowLayoutPanel:
                case K.WebBrowser:
                case K.Chart:
                case K.PrintPreviewControl:
                case K.ToolStripContainer: used.Widgets.Add("QFrame"); break;
                case K.TabControl: used.Widgets.Add("QTabWidget"); used.Widgets.Add("QWidget"); break;
                case K.SplitContainer: used.Widgets.Add("QSplitter"); used.NeedsQt = true; break;
                case K.TableLayoutPanel: used.Widgets.Add("QFrame"); used.Widgets.Add("QGridLayout"); break;
                case K.MenuStrip: used.Widgets.Add("QMenuBar"); break;
                case K.StatusStrip: used.Widgets.Add("QStatusBar"); break;
                case K.ContextMenuStrip: used.Widgets.Add("QMenu"); used.NeedsQt = true; break;
                case K.ToolStrip:
                case K.BindingNavigator: used.Widgets.Add("QToolBar"); break;
                case K.PictureBox: used.Widgets.Add("QLabel"); used.Gui.Add("QPixmap"); break;
                case K.Timer: used.Core.Add("QTimer"); break;
                case K.FileSystemWatcher: used.Core.Add("QFileSystemWatcher"); break;
                case K.Process: used.Core.Add("QProcess"); break;
                case K.NotifyIcon: used.Widgets.Add("QSystemTrayIcon"); break;
                case K.ToolTip: break;
                case K.ImageList: used.Gui.Add("QPixmap"); break;
                case K.OpenFileDialog:
                case K.SaveFileDialog:
                case K.FolderBrowserDialog: used.Widgets.Add("QFileDialog"); break;
                case K.FontDialog: used.Widgets.Add("QFontDialog"); break;
                case K.ColorDialog: used.Widgets.Add("QColorDialog"); break;
                default: break;
            }
        }

        private static UsedSymbols CollectSymbols(GuiForm form)
        {
            UsedSymbols used = new UsedSymbols();
            used.Widgets.Add("QApplication");
            used.Widgets.Add("QWidget");
            foreach (GuiControl c in form.Controls) CollectKindSymbols(c, used);
            return used;
        }

        private static string FormatImportList(SortedSet<string> syms)
        {
            StringBuilder o = new StringBuilder();
            bool first = true;
            int col = 0;
            foreach (string s in syms)
            {
                if (!first)
                {
                    o.Append(",");
                    if (col > 60) { o.Append("\n    "); col = 4; }
                    else { o.Append(" "); col++; }
                }
                else { o.Append("    "); col = 4; first = false; }
                o.Append(s);
                col += s.Length;
            }
            return o.ToString();
        }

        private static string BuildStyleSheet(GuiControl c)
        {
            StringBuilder ss = new StringBuilder();
            bool any = false;
            string fg = EC.PropOr(c, "ForeColor");
            string bg = EC.PropOr(c, "BackColor");
            if (fg.Length > 0) { if (any) ss.Append(" "); ss.Append("color: ").Append(fg).Append(";"); any = true; }
            if (bg.Length > 0) { if (any) ss.Append(" "); ss.Append("background-color: ").Append(bg).Append(";"); any = true; }
            return any ? ss.ToString() : "";
        }

        private static string SignalFor(string selfName, K kind, string eventName, string handler)
        {
            string Connect(string sig) => "        self." + selfName + "." + sig + ".connect(self." + handler + ")\n";
            if (eventName == "Click" || eventName == "command") return Connect("clicked");
            if (eventName == "TextChanged") return Connect("textChanged");
            if (eventName == "CheckedChanged" || eventName == "CheckStateChanged") return Connect("stateChanged");
            if (eventName == "ValueChanged") return Connect("valueChanged");
            if (eventName == "SelectedIndexChanged" || eventName == "SelectionChanged") return Connect("currentIndexChanged");
            if (eventName == "Tick") return Connect("timeout");
            if (eventName == "ItemActivate" || eventName == "DoubleClick") return Connect("doubleClicked");
            return "";
        }

        private static string QEventTypeFor(string eventName)
        {
            if (eventName == "MouseDown") return "QEvent.Type.MouseButtonPress";
            if (eventName == "MouseUp") return "QEvent.Type.MouseButtonRelease";
            if (eventName == "MouseMove") return "QEvent.Type.MouseMove";
            if (eventName == "MouseEnter") return "QEvent.Type.Enter";
            if (eventName == "MouseLeave") return "QEvent.Type.Leave";
            if (eventName == "MouseHover") return "QEvent.Type.HoverMove";
            if (eventName == "MouseWheel") return "QEvent.Type.Wheel";
            if (eventName == "MouseClick" || eventName == "MouseDoubleClick" || eventName == "DoubleClick")
                return "QEvent.Type.MouseButtonDblClick";
            if (eventName == "KeyDown") return "QEvent.Type.KeyPress";
            if (eventName == "KeyUp") return "QEvent.Type.KeyRelease";
            if (eventName == "KeyPress") return "QEvent.Type.KeyPress";
            if (eventName == "GotFocus" || eventName == "Enter") return "QEvent.Type.FocusIn";
            if (eventName == "LostFocus" || eventName == "Leave") return "QEvent.Type.FocusOut";
            if (eventName == "Resize" || eventName == "SizeChanged") return "QEvent.Type.Resize";
            if (eventName == "Paint") return "QEvent.Type.Paint";
            return "";
        }

        private static void EmitBuild(StringBuilder o, GuiControl c)
        {
            string self = "self." + EC.SafeMember(c.Name);
            string text = EC.PropOr(c, "Text", c.Name);
            string esc = EC.PyEscape(text);

            System.Action setGeom = () => o.Append("        ").Append(self).Append(".setGeometry(")
                .Append(c.X).Append(", ").Append(c.Y).Append(", ").Append(c.Width).Append(", ").Append(c.Height).Append(")\n");

            switch (c.Kind)
            {
                case K.Form: return;
                case K.Button:
                    o.Append("        ").Append(self).Append(" = QPushButton('").Append(esc).Append("', self)\n"); setGeom(); break;
                case K.Label:
                    o.Append("        ").Append(self).Append(" = QLabel('").Append(esc).Append("', self)\n"); setGeom(); break;
                case K.LinkLabel:
                    o.Append("        ").Append(self).Append(" = QLabel('").Append(esc).Append("', self)\n");
                    o.Append("        ").Append(self).Append(".setOpenExternalLinks(True)\n"); setGeom(); break;
                case K.TextBox:
                {
                    bool multi = EC.PropOr(c, "Multiline") == "True" || EC.PropOr(c, "Multiline") == "true";
                    if (multi)
                    {
                        o.Append("        ").Append(self).Append(" = QPlainTextEdit(self)\n");
                        if (text.Length > 0) o.Append("        ").Append(self).Append(".setPlainText('").Append(esc).Append("')\n");
                    }
                    else
                    {
                        o.Append("        ").Append(self).Append(" = QLineEdit(self)\n");
                        if (text.Length > 0) o.Append("        ").Append(self).Append(".setText('").Append(esc).Append("')\n");
                    }
                    setGeom(); break;
                }
                case K.MaskedTextBox:
                {
                    o.Append("        ").Append(self).Append(" = QLineEdit(self)\n");
                    string mask = EC.PropOr(c, "Mask");
                    if (mask.Length > 0) o.Append("        ").Append(self).Append(".setInputMask('").Append(EC.PyEscape(mask)).Append("')\n");
                    if (text.Length > 0) o.Append("        ").Append(self).Append(".setText('").Append(esc).Append("')\n");
                    setGeom(); break;
                }
                case K.RichTextBox:
                    o.Append("        ").Append(self).Append(" = QTextEdit(self)\n");
                    if (text.Length > 0) o.Append("        ").Append(self).Append(".setHtml('").Append(esc).Append("')\n");
                    setGeom(); break;
                case K.CheckBox:
                {
                    o.Append("        ").Append(self).Append(" = QCheckBox('").Append(esc).Append("', self)\n");
                    string ch = EC.PropOr(c, "Checked");
                    if (ch == "True" || ch == "true") o.Append("        ").Append(self).Append(".setChecked(True)\n");
                    setGeom(); break;
                }
                case K.RadioButton:
                {
                    o.Append("        ").Append(self).Append(" = QRadioButton('").Append(esc).Append("', self)\n");
                    string ch = EC.PropOr(c, "Checked");
                    if (ch == "True" || ch == "true") o.Append("        ").Append(self).Append(".setChecked(True)\n");
                    setGeom(); break;
                }
                case K.ComboBox:
                case K.DomainUpDown:
                {
                    o.Append("        ").Append(self).Append(" = QComboBox(self)\n");
                    List<string> items = EC.SplitCsv(EC.PropOr(c, "Items"));
                    if (items.Count == 0) items = EC.SplitCsv(EC.PropOr(c, "values"));
                    if (items.Count > 0) o.Append("        ").Append(self).Append(".addItems([").Append(JoinQuoted(items)).Append("])\n");
                    if (c.Kind == K.DomainUpDown) o.Append("        ").Append(self).Append(".setEditable(False)\n");
                    setGeom(); break;
                }
                case K.ListBox:
                case K.CheckedListBox:
                {
                    o.Append("        ").Append(self).Append(" = QListWidget(self)\n");
                    List<string> items = EC.SplitCsv(EC.PropOr(c, "Items"));
                    if (items.Count > 0) o.Append("        ").Append(self).Append(".addItems([").Append(JoinQuoted(items)).Append("])\n");
                    if (c.Kind == K.CheckedListBox)
                    {
                        o.Append("        for i in range(").Append(self).Append(".count()):\n");
                        o.Append("            it = ").Append(self).Append(".item(i)\n");
                        o.Append("            it.setFlags(it.flags() | Qt.ItemFlag.ItemIsUserCheckable)\n");
                        o.Append("            it.setCheckState(Qt.CheckState.Unchecked)\n");
                    }
                    setGeom(); break;
                }
                case K.ListView:
                {
                    o.Append("        ").Append(self).Append(" = QTreeWidget(self)\n");
                    List<string> cols = EC.SplitCsv(EC.PropOr(c, "Columns"));
                    if (cols.Count == 0) cols.Add("Column");
                    o.Append("        ").Append(self).Append(".setHeaderLabels([").Append(JoinQuoted(cols)).Append("])\n");
                    setGeom(); break;
                }
                case K.TreeView:
                    o.Append("        ").Append(self).Append(" = QTreeWidget(self)\n");
                    o.Append("        ").Append(self).Append(".setHeaderHidden(True)\n"); setGeom(); break;
                case K.ProgressBar:
                {
                    o.Append("        ").Append(self).Append(" = QProgressBar(self)\n");
                    o.Append("        ").Append(self).Append(".setRange(").Append(EC.IntPropOr(c, "Minimum", 0)).Append(", ").Append(EC.IntPropOr(c, "Maximum", 100)).Append(")\n");
                    o.Append("        ").Append(self).Append(".setValue(").Append(EC.IntPropOr(c, "Value", 0)).Append(")\n");
                    setGeom(); break;
                }
                case K.TrackBar:
                {
                    o.Append("        ").Append(self).Append(" = QSlider(Qt.Orientation.Horizontal, self)\n");
                    o.Append("        ").Append(self).Append(".setRange(").Append(EC.IntPropOr(c, "Minimum", 0)).Append(", ").Append(EC.IntPropOr(c, "Maximum", 10)).Append(")\n");
                    o.Append("        ").Append(self).Append(".setValue(").Append(EC.IntPropOr(c, "Value", 0)).Append(")\n");
                    setGeom(); break;
                }
                case K.NumericUpDown:
                {
                    o.Append("        ").Append(self).Append(" = QSpinBox(self)\n");
                    o.Append("        ").Append(self).Append(".setRange(").Append(EC.IntPropOr(c, "Minimum", 0)).Append(", ").Append(EC.IntPropOr(c, "Maximum", 100)).Append(")\n");
                    o.Append("        ").Append(self).Append(".setValue(").Append(EC.IntPropOr(c, "Value", 0)).Append(")\n");
                    setGeom(); break;
                }
                case K.DateTimePicker:
                    o.Append("        ").Append(self).Append(" = QDateTimeEdit(self)\n"); setGeom(); break;
                case K.MonthCalendar:
                    o.Append("        ").Append(self).Append(" = QCalendarWidget(self)\n"); setGeom(); break;
                case K.GroupBox:
                    o.Append("        ").Append(self).Append(" = QGroupBox('").Append(esc).Append("', self)\n"); setGeom(); break;
                case K.Panel:
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n");
                    o.Append("        ").Append(self).Append(".setFrameShape(QFrame.Shape.Box)\n"); setGeom(); break;
                case K.FlowLayoutPanel:
                    o.Append("        # TODO: FlowLayoutPanel needs a custom flow layout; using QFrame placeholder.\n");
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n"); setGeom(); break;
                case K.TabControl:
                {
                    o.Append("        ").Append(self).Append(" = QTabWidget(self)\n");
                    List<string> pages = EC.SplitCsv(EC.PropOr(c, "TabPages"));
                    if (pages.Count == 0) pages.Add("Page1");
                    foreach (string p in pages) o.Append("        ").Append(self).Append(".addTab(QWidget(), '").Append(EC.PyEscape(p)).Append("')\n");
                    setGeom(); break;
                }
                case K.SplitContainer:
                {
                    bool vertical = EC.PropOr(c, "Orientation") == "Vertical";
                    o.Append("        ").Append(self).Append(" = QSplitter(")
                        .Append(vertical ? "Qt.Orientation.Vertical" : "Qt.Orientation.Horizontal").Append(", self)\n");
                    setGeom(); break;
                }
                case K.TableLayoutPanel:
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n");
                    o.Append("        ").Append(self).Append(".setLayout(QGridLayout())\n"); setGeom(); break;
                case K.MenuStrip:
                    o.Append("        # NOTE: MenuStrip works best on QMainWindow; on QWidget it renders as a child QMenuBar.\n");
                    o.Append("        ").Append(self).Append(" = QMenuBar(self)\n"); setGeom(); break;
                case K.StatusStrip:
                    o.Append("        ").Append(self).Append(" = QStatusBar(self)\n"); setGeom(); break;
                case K.ContextMenuStrip:
                    o.Append("        ").Append(self).Append(" = QMenu(self)\n");
                    o.Append("        self.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)\n"); break;
                case K.ToolStrip:
                case K.BindingNavigator:
                    o.Append("        ").Append(self).Append(" = QToolBar(self)\n"); setGeom(); break;
                case K.ToolStripContainer:
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n"); setGeom(); break;
                case K.PictureBox:
                {
                    o.Append("        ").Append(self).Append(" = QLabel(self)\n");
                    string img = EC.PropOr(c, "Image");
                    if (img.Length > 0)
                    {
                        o.Append("        ").Append(self).Append(".setPixmap(QPixmap('").Append(EC.PyEscape(img)).Append("'))\n");
                        o.Append("        ").Append(self).Append(".setScaledContents(True)\n");
                    }
                    setGeom(); break;
                }
                case K.WebBrowser:
                    o.Append("        # TODO: WebBrowser needs PyQt6-WebEngine (QWebEngineView). Placeholder QFrame for now.\n");
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n"); setGeom(); break;
                case K.DataGridView:
                    o.Append("        # TODO: DataGridView placeholder — use QTableWidget for an editable grid.\n");
                    o.Append("        ").Append(self).Append(" = QTreeWidget(self)\n");
                    o.Append("        ").Append(self).Append(".setHeaderLabels(['Column1', 'Column2'])\n"); setGeom(); break;
                case K.Chart:
                    o.Append("        # TODO: Chart placeholder — consider PyQtChart / PyQtGraph.\n");
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n"); setGeom(); break;
                case K.PrintPreviewControl:
                    o.Append("        # TODO: PrintPreviewControl — use QPrintPreviewWidget from QtPrintSupport.\n");
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n"); setGeom(); break;
                case K.Timer:
                {
                    o.Append("        ").Append(self).Append(" = QTimer(self)\n");
                    o.Append("        ").Append(self).Append(".setInterval(").Append(EC.IntPropOr(c, "Interval", 1000)).Append(")\n");
                    string en = EC.PropOr(c, "Enabled");
                    if (en == "True" || en == "true") o.Append("        ").Append(self).Append(".start()\n");
                    break;
                }
                case K.FileSystemWatcher:
                    o.Append("        ").Append(self).Append(" = QFileSystemWatcher(self)\n"); break;
                case K.Process:
                    o.Append("        ").Append(self).Append(" = QProcess(self)\n"); break;
                case K.NotifyIcon:
                    o.Append("        ").Append(self).Append(" = QSystemTrayIcon(self)\n"); break;
                case K.ToolTip:
                    return;
                case K.ImageList:
                    o.Append("        ").Append(self).Append(" = {}  # name -> QPixmap\n"); break;
                case K.BackgroundWorker:
                    o.Append("        # TODO: BackgroundWorker — use QThread or QtConcurrent.\n");
                    o.Append("        ").Append(self).Append(" = None\n"); break;
                case K.ColorDialog:
                case K.FolderBrowserDialog:
                case K.FontDialog:
                case K.OpenFileDialog:
                case K.SaveFileDialog:
                    o.Append("        # ").Append(GuiControlKinds.ToToken(c.Kind))
                        .Append(" is invoked via self.show_").Append(EC.SafeMember(c.Name)).Append("()\n");
                    return;
                case K.ErrorProvider:
                case K.HelpProvider:
                case K.SerialPort:
                case K.BindingSource:
                case K.DataSet:
                case K.PrintDocument:
                case K.PageSetupDialog:
                case K.PrintDialog:
                case K.PrintPreviewDialog:
                    o.Append("        # TODO: ").Append(GuiControlKinds.ToToken(c.Kind))
                        .Append(" — no direct PyQt6 equivalent; resolve in user code.\n");
                    o.Append("        ").Append(self).Append(" = None\n"); break;
                default:
                    o.Append("        # TODO: Unsupported control kind ").Append(GuiControlKinds.ToToken(c.Kind)).Append("\n");
                    o.Append("        ").Append(self).Append(" = QFrame(self)\n"); setGeom(); break;
            }

            // applyEnabled / Visible / Tooltip / Accessibility / Style
            string enabled = EC.PropOr(c, "Enabled");
            if (enabled == "False" || enabled == "false") o.Append("        ").Append(self).Append(".setEnabled(False)\n");
            string visible = EC.PropOr(c, "Visible");
            if (visible == "False" || visible == "false") o.Append("        ").Append(self).Append(".setVisible(False)\n");
            string tt = EC.PropOr(c, "ToolTip");
            if (tt.Length > 0) o.Append("        ").Append(self).Append(".setToolTip('").Append(EC.PyEscape(tt)).Append("')\n");
            string accName = EC.PropOr(c, "AccessibleName");
            string accDesc = EC.PropOr(c, "AccessibleDescription");
            if (accName.Length > 0) o.Append("        ").Append(self).Append(".setAccessibleName('").Append(EC.PyEscape(accName)).Append("')\n");
            if (accDesc.Length > 0) o.Append("        ").Append(self).Append(".setAccessibleDescription('").Append(EC.PyEscape(accDesc)).Append("')\n");
            string css = BuildStyleSheet(c);
            if (css.Length > 0) o.Append("        ").Append(self).Append(".setStyleSheet('").Append(EC.PyEscape(css)).Append("')\n");
        }

        private static string JoinQuoted(List<string> items)
        {
            StringBuilder sb = new StringBuilder();
            bool first = true;
            foreach (string it in items)
            {
                if (!first) sb.Append(", ");
                sb.Append("'").Append(EC.PyEscape(it)).Append("'");
                first = false;
            }
            return sb.ToString();
        }

        public string Emit(GuiForm form, string existingSource)
        {
            Dictionary<string, string> regions = CodeRegionPreserver.Parse(existingSource);
            UsedSymbols used = CollectSymbols(form);

            bool needsEventFilter = false;
            foreach (GuiControl c in form.Controls)
            {
                if (c.Kind == K.Form) continue;
                foreach (GuiEvent e in c.Events)
                {
                    if (string.IsNullOrEmpty(e.HandlerName)) continue;
                    if (SignalFor(EC.SafeMember(c.Name), c.Kind, e.EventName, e.HandlerName).Length > 0) continue;
                    if (QEventTypeFor(e.EventName).Length > 0) { needsEventFilter = true; break; }
                }
                if (needsEventFilter) break;
            }

            StringBuilder o = new StringBuilder();
            o.Append(EC.AutoGenBanner());

            // QtCore imports.
            {
                SortedSet<string> core = new SortedSet<string>(used.Core, System.StringComparer.Ordinal);
                if (used.NeedsQt) core.Add("Qt");
                if (needsEventFilter) { core.Add("QEvent"); core.Add("QObject"); }
                if (core.Count > 0)
                {
                    o.Append("from ").Append(ImportPrefix).Append(".QtCore import ");
                    o.Append(string.Join(", ", core));
                    o.Append("\n");
                }
            }
            if (used.Gui.Count > 0)
            {
                o.Append("from ").Append(ImportPrefix).Append(".QtGui import ");
                o.Append(string.Join(", ", used.Gui));
                o.Append("\n");
            }
            o.Append("from ").Append(ImportPrefix).Append(".QtWidgets import (\n").Append(FormatImportList(used.Widgets)).Append(",\n)\n");

            o.Append("\n\n");
            if (needsEventFilter)
            {
                o.Append("class _EventFilter(QObject):\n");
                o.Append("    \"\"\"Routes specific QEvent.Types from a widget to callable handlers.\n\n");
                o.Append("    Used for events without a direct PyQt6 signal — mouse moves, key presses, focus,\n");
                o.Append("    paint, resize. The dict maps QEvent.Type → handler; unmapped events pass through.\n");
                o.Append("    \"\"\"\n");
                o.Append("    def __init__(self, widget, event_map):\n");
                o.Append("        super().__init__(widget)\n");
                o.Append("        self._map = event_map\n");
                o.Append("        widget.installEventFilter(self)\n");
                o.Append("\n");
                o.Append("    def eventFilter(self, obj, event):\n");
                o.Append("        cb = self._map.get(event.type())\n");
                o.Append("        if cb is not None:\n");
                o.Append("            cb(event)\n");
                o.Append("        return False\n");
                o.Append("\n\n");
            }
            o.Append("class ").Append(form.FormClassName).Append("(QWidget):\n");
            o.Append("    def __init__(self, parent=None):\n");
            o.Append("        super().__init__(parent)\n");
            o.Append("        self.setWindowTitle('").Append(EC.PyEscape(form.Title)).Append("')\n");
            o.Append("        self.resize(").Append(form.Width).Append(", ").Append(form.Height).Append(")\n");
            o.Append("        self._build_ui()\n");
            o.Append("        self._wire_events()\n");
            o.Append("\n");

            o.Append("    def _build_ui(self):\n");
            bool emittedAny = false;
            foreach (GuiControl c in form.Controls)
            {
                if (c.Kind == K.Form) continue;
                EmitBuild(o, c);
                emittedAny = true;
            }
            if (!emittedAny) o.Append("        pass\n");
            o.Append("\n");

            o.Append("    def _wire_events(self):\n");
            bool anyWired = false;
            foreach (GuiControl c in form.Controls)
            {
                if (c.Kind == K.Form || c.Kind == K.ToolTip) continue;
                string member = EC.SafeMember(c.Name);
                List<KeyValuePair<string, string>> filterEntries = new List<KeyValuePair<string, string>>();
                foreach (GuiEvent e in c.Events)
                {
                    if (string.IsNullOrEmpty(e.HandlerName)) continue;
                    string line = SignalFor(member, c.Kind, e.EventName, e.HandlerName);
                    if (line.Length > 0) { o.Append(line); anyWired = true; continue; }
                    string qevent = QEventTypeFor(e.EventName);
                    if (qevent.Length == 0)
                    {
                        o.Append("        # TODO: '").Append(e.EventName)
                            .Append("' has no direct signal or QEvent mapping on ").Append(GuiControlKinds.ToToken(c.Kind))
                            .Append("; route to self.").Append(e.HandlerName).Append(" manually.\n");
                        anyWired = true;
                        continue;
                    }
                    filterEntries.Add(new KeyValuePair<string, string>(qevent, e.HandlerName));
                    anyWired = true;
                }
                if (filterEntries.Count > 0)
                {
                    o.Append("        self._").Append(member).Append("_filter = _EventFilter(\n");
                    o.Append("            self.").Append(member).Append(",\n");
                    o.Append("            {\n");
                    foreach (KeyValuePair<string, string> fe in filterEntries)
                        o.Append("                ").Append(fe.Key).Append(": self.").Append(fe.Value).Append(",\n");
                    o.Append("            },\n");
                    o.Append("        )\n");
                }
            }
            if (!anyWired) o.Append("        pass\n");
            o.Append("\n");

            foreach (GuiControl c in form.Controls)
            {
                string member = EC.SafeMember(c.Name);
                string title = EC.PropOr(c, "Title", c.Name);
                string filter = EC.PropOr(c, "Filter");
                string initdir = EC.PropOr(c, "InitialDirectory");
                switch (c.Kind)
                {
                    case K.OpenFileDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        path, _ = QFileDialog.getOpenFileName(\n");
                        o.Append("            self, '").Append(EC.PyEscape(title)).Append("', '").Append(EC.PyEscape(initdir)).Append("', '").Append(EC.PyEscape(filter)).Append("')\n");
                        o.Append("        return path\n\n");
                        break;
                    case K.SaveFileDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        path, _ = QFileDialog.getSaveFileName(\n");
                        o.Append("            self, '").Append(EC.PyEscape(title)).Append("', '").Append(EC.PyEscape(initdir)).Append("', '").Append(EC.PyEscape(filter)).Append("')\n");
                        o.Append("        return path\n\n");
                        break;
                    case K.FolderBrowserDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        return QFileDialog.getExistingDirectory(\n");
                        o.Append("            self, '").Append(EC.PyEscape(title)).Append("', '").Append(EC.PyEscape(initdir)).Append("')\n\n");
                        break;
                    case K.FontDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        font, ok = QFontDialog.getFont(self)\n");
                        o.Append("        return font if ok else None\n\n");
                        break;
                    case K.ColorDialog:
                        o.Append("    def show_").Append(member).Append("(self):\n");
                        o.Append("        c = QColorDialog.getColor(parent=self)\n");
                        o.Append("        return c if c.isValid() else None\n\n");
                        break;
                    default: break;
                }
            }

            {
                string regionName = "UserCode-handlers";
                StringBuilder defaultBody = new StringBuilder();
                HashSet<string> emitted = new HashSet<string>(System.StringComparer.Ordinal);
                foreach (GuiControl c in form.Controls)
                    foreach (GuiEvent e in c.Events)
                    {
                        if (string.IsNullOrEmpty(e.HandlerName)) continue;
                        if (!emitted.Add(e.HandlerName)) continue;
                        defaultBody.Append("def ").Append(e.HandlerName).Append("(*args, **kwargs):\n    pass\n\n");
                    }
                if (defaultBody.Length == 0) defaultBody.Append("# Add custom handlers here.\n");
                o.Append("# region ").Append(regionName).Append("\n");
                o.Append(CodeRegionPreserver.GetOrDefault(regions, regionName, defaultBody.ToString()));
                o.Append("# endregion\n\n");
            }

            {
                string regionName = "UserCode-main";
                string defaultBody =
                    "if __name__ == '__main__':\n" +
                    "    import sys\n" +
                    "    app = QApplication(sys.argv)\n" +
                    "    win = " + form.FormClassName + "()\n" +
                    "    win.show()\n" +
                    "    sys.exit(app.exec())\n";
                o.Append("# region ").Append(regionName).Append("\n");
                o.Append(CodeRegionPreserver.GetOrDefault(regions, regionName, defaultBody));
                o.Append("# endregion\n");
            }

            return o.ToString();
        }
    }
