namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using System.Collections.Generic;
    using System.Text;
    using HelixPythonNamespace.GuiDesigner.Model;
    using K = HelixPythonNamespace.GuiDesigner.Model.GuiControlKind;

    /// <summary>Generates a Tkinter module from a GuiForm. Port of the C++ <c>TkinterEmitter</c>.</summary>
    public sealed class TkinterEmitter : IGuiCodeEmitter
    {
        public string FrameworkName { get { return "Tkinter"; } }
        public string SourceExtension { get { return ".py"; } }
        public string AutoGeneratedMarker { get { return "# AUTO-GENERATED by HelixPython."; } }

        // (namespace, ctor): "tk"/"ttk".
        private static void CtorFor(K kind, out string ns, out string ctor)
        {
            switch (kind)
            {
                case K.Button: ns = "tk"; ctor = "Button"; return;
                case K.Label: ns = "tk"; ctor = "Label"; return;
                case K.TextBox: ns = "tk"; ctor = "Entry"; return;
                case K.RichTextBox: ns = "tk"; ctor = "Text"; return;
                case K.CheckBox: ns = "tk"; ctor = "Checkbutton"; return;
                case K.RadioButton: ns = "tk"; ctor = "Radiobutton"; return;
                case K.ComboBox: ns = "ttk"; ctor = "Combobox"; return;
                case K.ListBox: ns = "tk"; ctor = "Listbox"; return;
                case K.CheckedListBox: ns = "tk"; ctor = "Listbox"; return;
                case K.TrackBar: ns = "ttk"; ctor = "Scale"; return;
                case K.NumericUpDown: ns = "ttk"; ctor = "Spinbox"; return;
                case K.DomainUpDown: ns = "ttk"; ctor = "Spinbox"; return;
                case K.ProgressBar: ns = "ttk"; ctor = "Progressbar"; return;
                case K.Panel: ns = "tk"; ctor = "Frame"; return;
                case K.GroupBox: ns = "tk"; ctor = "LabelFrame"; return;
                case K.FlowLayoutPanel: ns = "tk"; ctor = "Frame"; return;
                case K.SplitContainer: ns = "tk"; ctor = "PanedWindow"; return;
                case K.TabControl: ns = "ttk"; ctor = "Notebook"; return;
                case K.TableLayoutPanel: ns = "tk"; ctor = "Frame"; return;
                case K.ToolStripContainer: ns = "tk"; ctor = "Frame"; return;
                case K.PictureBox: ns = "tk"; ctor = "Label"; return;
                case K.LinkLabel: ns = "tk"; ctor = "Label"; return;
                case K.TreeView: ns = "ttk"; ctor = "Treeview"; return;
                case K.ListView: ns = "ttk"; ctor = "Treeview"; return;
                case K.Form: ns = "tk"; ctor = "Frame"; return;
                default: ns = "tk"; ctor = "Frame"; return; // placeholder kinds
            }
        }

        /// <summary>
        /// The constructor call for a control the support module provides, or null when Tk has a
        /// widget of its own. See <see cref="TkinterRuntime"/> for why eighteen of the toolbox's
        /// controls need one.
        /// </summary>
        private static string RuntimeCtor(GuiControl c, string parentPyExpr)
        {
            string cls = TkinterRuntime.ClassFor(c.Kind);
            if (cls == null) return null;

            switch (c.Kind)
            {
                // Visual widgets: ordinary children of their parent.
                case K.DataGridView:
                    return cls + "(" + parentPyExpr + ", columns=" + PyTuple(EmitterCommon.PropOr(c, "Columns", "Column")) + ")";
                case K.Chart:
                    return cls + "(" + parentPyExpr + ", title='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Title", "")) + "')";
                case K.MaskedTextBox:
                    return cls + "(" + parentPyExpr + ", mask='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Mask", "")) + "')";
                case K.WebBrowser:
                    return cls + "(" + parentPyExpr + ", url='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Url", "")) + "')";
                case K.MonthCalendar:
                case K.DateTimePicker:
                case K.BindingNavigator:
                case K.ToolStrip:
                case K.StatusStrip:
                    return cls + "(" + parentPyExpr + ")";

                // A Tk menubar belongs to the TOPLEVEL, not to this frame -- that is the whole
                // reason it cannot be placed like a widget.
                case K.MenuStrip:
                    return cls + "(self.winfo_toplevel())";
                case K.ContextMenuStrip:
                    return cls + "(self)";

                // Non-visual components. They take no parent except where they need a widget to
                // schedule against or to parent a popup onto.
                case K.Timer:
                    return cls + "(self, interval=" + IntOr(EmitterCommon.PropOr(c, "Interval", "1000"), 1000)
                        + ", enabled=" + PyBool(EmitterCommon.PropOr(c, "Enabled", "False")) + ")";
                case K.NotifyIcon:
                    return cls + "(self, title='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Text", "")) + "')";
                case K.ToolTip:
                    return cls + "(delay=" + IntOr(EmitterCommon.PropOr(c, "InitialDelay", "500"), 500) + ")";
                case K.ImageList:
                    return cls + "(" + PyTuple(EmitterCommon.PropOr(c, "Images", "")) + ")";
                case K.ErrorProvider:
                case K.BindingSource:
                    return cls + "()";
                case K.OpenFileDialog:
                case K.SaveFileDialog:
                    return cls + "(title='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Title", "")) + "'"
                        + ", filter_text='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Filter", "All files|*.*")) + "')";
                case K.FolderBrowserDialog:
                case K.ColorDialog:
                case K.FontDialog:
                    return cls + "(title='" + EmitterCommon.PyEscape(EmitterCommon.PropOr(c, "Title", "")) + "')";
            }
            return cls + "()";
        }

        /// <summary>A comma-separated property as a Python tuple literal; () when empty.</summary>
        private static string PyTuple(string commaSeparated)
        {
            var items = new List<string>();
            foreach (string raw in (commaSeparated ?? string.Empty).Split(','))
            {
                string trimmed = raw.Trim();
                if (trimmed.Length > 0) items.Add("'" + EmitterCommon.PyEscape(trimmed) + "'");
            }
            if (items.Count == 0) return "()";
            // A one-element tuple needs the trailing comma or Python reads it as a parenthesised
            // string, and the widget then gets one column per CHARACTER.
            return items.Count == 1 ? "(" + items[0] + ",)" : "(" + string.Join(", ", items) + ")";
        }

        private static string PyBool(string value)
        {
            return string.Equals(value, "true", System.StringComparison.OrdinalIgnoreCase) ? "True" : "False";
        }

        private static string IntOr(string value, int fallback)
        {
            int parsed;
            return int.TryParse(value, out parsed) ? parsed.ToString() : fallback.ToString();
        }

        private static readonly Dictionary<string, string> WinFormsToTk = new Dictionary<string, string>(System.StringComparer.Ordinal)
        {
            { "Text", "text" }, { "BackColor", "bg" }, { "ForeColor", "fg" },
            { "Cursor", "cursor" }, { "Font", "font" },
        };

        private static SortedDictionary<string, string> CleanPropsForTkinter(IDictionary<string, string> raw)
        {
            SortedDictionary<string, string> outMap = new SortedDictionary<string, string>(System.StringComparer.Ordinal);
            foreach (KeyValuePair<string, string> kv in raw)
            {
                string k = kv.Key, v = kv.Value;
                if (string.IsNullOrEmpty(v) || string.IsNullOrEmpty(k)) continue;
                if (k[0] >= 'a' && k[0] <= 'z') { outMap[k] = v; continue; } // already Tkinter-style
                string mapped;
                if (WinFormsToTk.TryGetValue(k, out mapped)) outMap[mapped] = v;
                // else drop WinForms-only keys
            }
            return outMap;
        }

        private static readonly Dictionary<string, HashSet<string>> Allowlist = BuildAllowlist();

        private static Dictionary<string, HashSet<string>> BuildAllowlist()
        {
            Dictionary<string, HashSet<string>> m = new Dictionary<string, HashSet<string>>(System.StringComparer.Ordinal);
            System.Action<string, string, string[]> add = (ns, ctor, keys) =>
                m[ns + "." + ctor] = new HashSet<string>(keys, System.StringComparer.Ordinal);
            add("tk", "Button", new[] { "text", "bg", "fg", "font", "cursor" });
            add("tk", "Label", new[] { "text", "bg", "fg", "font", "cursor" });
            add("tk", "LabelFrame", new[] { "text", "bg", "fg", "font", "cursor" });
            add("tk", "Checkbutton", new[] { "text", "bg", "fg", "font", "cursor" });
            add("tk", "Radiobutton", new[] { "text", "bg", "fg", "font", "cursor", "value" });
            add("tk", "Entry", new[] { "bg", "fg", "font", "cursor" });
            add("tk", "Text", new[] { "bg", "fg", "font", "cursor" });
            add("tk", "Listbox", new[] { "bg", "fg", "font", "cursor" });
            add("tk", "Frame", new[] { "bg", "cursor" });
            add("tk", "PanedWindow", new[] { "bg", "cursor" });
            add("ttk", "Combobox", new[] { "cursor", "values" });
            add("ttk", "Notebook", new[] { "cursor" });
            add("ttk", "Treeview", new[] { "cursor" });
            add("ttk", "Spinbox", new[] { "cursor", "values", "from_", "to", "increment" });
            add("ttk", "Scale", new[] { "cursor", "from_", "to", "value" });
            add("ttk", "Progressbar", new[] { "cursor", "value" });
            return m;
        }

        private static SortedDictionary<string, string> FilterForCtor(string ns, string ctor, SortedDictionary<string, string> clean)
        {
            HashSet<string> allowed;
            if (!Allowlist.TryGetValue(ns + "." + ctor, out allowed)) return clean; // unknown ctor — pass through
            SortedDictionary<string, string> outMap = new SortedDictionary<string, string>(System.StringComparer.Ordinal);
            foreach (KeyValuePair<string, string> kv in clean)
                if (allowed.Contains(kv.Key)) outMap[kv.Key] = kv.Value;
            return outMap;
        }

        private static readonly Dictionary<string, string> CursorMap = new Dictionary<string, string>(System.StringComparer.Ordinal)
        {
            { "Default", "" }, { "Arrow", "arrow" }, { "Cross", "cross" }, { "Hand", "hand2" },
            { "Help", "question_arrow" }, { "HSplit", "sb_h_double_arrow" }, { "IBeam", "xterm" },
            { "No", "X_cursor" }, { "PanEast", "sb_right_arrow" }, { "PanNE", "top_right_corner" },
            { "PanNorth", "sb_up_arrow" }, { "PanNW", "top_left_corner" }, { "PanSE", "bottom_right_corner" },
            { "PanSouth", "sb_down_arrow" }, { "PanSW", "bottom_left_corner" }, { "PanWest", "sb_left_arrow" },
            { "SizeAll", "fleur" }, { "SizeNESW", "bottom_left_corner" }, { "SizeNS", "sb_v_double_arrow" },
            { "SizeNWSE", "bottom_right_corner" }, { "SizeWE", "sb_h_double_arrow" }, { "UpArrow", "based_arrow_up" },
            { "VSplit", "sb_v_double_arrow" }, { "WaitCursor", "watch" },
        };

        private static string CursorToTk(string winFormsCursor)
        {
            string v;
            return CursorMap.TryGetValue(winFormsCursor, out v) ? v : "";
        }

        private static string FontToTk(string winFormsFont)
        {
            string[] rawParts = winFormsFont.Split(';');
            List<string> parts = new List<string>();
            foreach (string p in rawParts) parts.Add(p.Trim());
            if (parts.Count == 0 || parts[0].Length == 0) return "";

            StringBuilder tk = new StringBuilder();
            string family = parts[0];
            if (family.IndexOf(' ') >= 0) tk.Append("{").Append(family).Append("}");
            else tk.Append(family);
            if (parts.Count >= 2 && IsInt(parts[1])) tk.Append(" ").Append(parts[1]);
            if (parts.Count >= 3)
            {
                foreach (string raw in parts[2].Split(','))
                {
                    string st = raw.Trim().ToLowerInvariant();
                    if (st.Length == 0 || st == "regular") continue;
                    tk.Append(" ").Append(st);
                }
            }
            return tk.ToString();
        }

        private static bool IsInt(string s)
        {
            if (string.IsNullOrEmpty(s)) return false;
            int i = s[0] == '-' ? 1 : 0;
            if (i == s.Length) return false;
            for (; i < s.Length; i++) if (s[i] < '0' || s[i] > '9') return false;
            return true;
        }

        private static string PropArg(string key, string value)
        {
            if (key == "from_" || key == "to" || key == "maximum")
                return key + "=" + (string.IsNullOrEmpty(value) ? "0" : value);
            if (key == "values")
            {
                StringBuilder tup = new StringBuilder("values=(");
                bool first = true;
                foreach (string raw in value.Split(','))
                {
                    if (!first) tup.Append(", ");
                    tup.Append("'").Append(EmitterCommon.PyEscape(raw)).Append("'");
                    first = false;
                }
                tup.Append(")");
                return tup.ToString();
            }
            return key + "='" + EmitterCommon.PyEscape(value) + "'";
        }

        // ---- Parent/child tree support (containers with composed children, e.g. a Notebook holding
        // custom-class panels) — additive on top of the original flat model. A control with an empty
        // or unresolved ParentId is a root; PLACEMENT ORDER within each parent's child list mirrors
        // GuiForm.Controls' original relative order, so an all-flat form (every ParentId empty, the
        // shape every existing form/test uses) produces byte-identical output to before this existed.

        private static Dictionary<string, List<GuiControl>> BuildChildrenMap(List<GuiControl> controls, out List<GuiControl> roots)
        {
            var byId = new Dictionary<string, GuiControl>(System.StringComparer.Ordinal);
            foreach (GuiControl c in controls)
                if (!string.IsNullOrEmpty(c.Id)) byId[c.Id] = c;

            var childrenOf = new Dictionary<string, List<GuiControl>>(System.StringComparer.Ordinal);
            roots = new List<GuiControl>();
            foreach (GuiControl c in controls)
            {
                string pid = c.ParentId;
                if (string.IsNullOrEmpty(pid) || !byId.ContainsKey(pid)) { roots.Add(c); continue; }
                List<GuiControl> list;
                if (!childrenOf.TryGetValue(pid, out list)) { list = new List<GuiControl>(); childrenOf[pid] = list; }
                list.Add(c);
            }
            return childrenOf;
        }

        // `from Module import ClassA, ClassB` lines for every distinct CustomComponent, sorted for
        // deterministic output.
        private static void EmitCustomComponentImports(StringBuilder o, GuiForm form)
        {
            var byModule = new SortedDictionary<string, List<string>>(System.StringComparer.Ordinal);
            foreach (GuiControl c in form.Controls)
            {
                if (c.Kind != K.CustomComponent) continue;
                string module = EmitterCommon.PropOr(c, "Module", "");
                string className = EmitterCommon.PropOr(c, "ClassName", "");
                if (module.Length == 0 || className.Length == 0) continue;
                List<string> names;
                if (!byModule.TryGetValue(module, out names)) { names = new List<string>(); byModule[module] = names; }
                if (!names.Contains(className)) names.Add(className);
            }
            foreach (KeyValuePair<string, List<string>> kv in byModule)
            {
                kv.Value.Sort(System.StringComparer.Ordinal);
                o.Append("from ").Append(kv.Key).Append(" import ").Append(string.Join(", ", kv.Value)).Append("\n");
            }
        }

        // Emits one control's construction + placement line(s), then recurses into its children (if
        // any) with `self.{c.Name}` as their parent widget expression.
        private static void EmitControlAndChildren(StringBuilder o, GuiControl c, string parentPyExpr,
            Dictionary<string, GuiControl> byId, Dictionary<string, List<GuiControl>> childrenOf)
        {
            string locked;
            if (c.Props.TryGetValue("Locked", out locked) && locked.ToLowerInvariant() == "true")
                o.Append("        # locked: ").Append(c.Name).Append(" (designer)\n");

            if (c.Kind == K.CustomComponent)
            {
                string className = EmitterCommon.PropOr(c, "ClassName", "tk.Frame");
                o.Append("        self.").Append(c.Name).Append(" = ").Append(className).Append("(").Append(parentPyExpr).Append(")\n");
            }
            else if (TkinterRuntime.ClassFor(c.Kind) != null)
            {
                o.Append("        self.").Append(c.Name).Append(" = ").Append(RuntimeCtor(c, parentPyExpr)).Append("\n");
            }
            else
            {
                string ns, ctor;
                CtorFor(c.Kind, out ns, out ctor);
                o.Append("        self.").Append(c.Name).Append(" = ").Append(ns).Append(".").Append(ctor).Append("(").Append(parentPyExpr);
                SortedDictionary<string, string> clean = CleanPropsForTkinter(c.Props);
                SortedDictionary<string, string> safe = FilterForCtor(ns, ctor, clean);
                foreach (KeyValuePair<string, string> kv in safe)
                {
                    if (kv.Key == "cursor")
                    {
                        string tkCur = CursorToTk(kv.Value);
                        if (tkCur.Length == 0) continue;
                        o.Append(", ").Append(PropArg(kv.Key, tkCur));
                        continue;
                    }
                    if (kv.Key == "font")
                    {
                        string tkFont = FontToTk(kv.Value);
                        if (tkFont.Length == 0) continue;
                        o.Append(", ").Append(PropArg(kv.Key, tkFont));
                        continue;
                    }
                    o.Append(", ").Append(PropArg(kv.Key, kv.Value));
                }
                o.Append(")\n");
            }

            // A Notebook (TabControl) child is added via .add(...), never independently placed. A
            // control opted into Pack layout (Props["Layout"]="Pack", e.g. a panel that fills its
            // parent rather than sitting at an absolute position) uses .pack(...). Everything else
            // keeps the original absolute .place(x=,y=,width=,height=) behavior.
            // A non-visual component has no geometry to give. Placing one produced the defect this
            // whole path exists to fix: a Timer, a SaveFileDialog and a ToolTip each drawn as a
            // grey rectangle on the form, in the spot the designer happened to drop them.
            // The menubar is placeless for a different reason -- it belongs to the toplevel.
            if (GuiControlKinds.IsNonVisualComponent(c.Kind) || c.Kind == K.MenuStrip
                || c.Kind == K.ContextMenuStrip)
            {
                return;
            }

            GuiControl parent;
            bool parentIsNotebook = !string.IsNullOrEmpty(c.ParentId) && byId.TryGetValue(c.ParentId, out parent) && parent.Kind == K.TabControl;
            if (parentIsNotebook)
            {
                string tabTitle = EmitterCommon.PropOr(c, "TabTitle", c.Name);
                o.Append("        ").Append(parentPyExpr).Append(".add(self.").Append(c.Name)
                    .Append(", text='").Append(EmitterCommon.PyEscape(tabTitle)).Append("')\n");
            }
            else if (string.Equals(EmitterCommon.PropOr(c, "Layout", "Place"), "Pack", System.StringComparison.OrdinalIgnoreCase))
            {
                var packArgs = new List<string>();
                string side = EmitterCommon.PropOr(c, "PackSide", "");
                if (side.Length > 0) packArgs.Add("side='" + EmitterCommon.PyEscape(side) + "'");
                string fill = EmitterCommon.PropOr(c, "PackFill", "both");
                if (fill.Length > 0) packArgs.Add("fill='" + EmitterCommon.PyEscape(fill) + "'");
                string expand = EmitterCommon.PropOr(c, "PackExpand", "True");
                if (expand.Length > 0) packArgs.Add("expand=" + expand);
                o.Append("        self.").Append(c.Name).Append(".pack(").Append(string.Join(", ", packArgs)).Append(")\n");
            }
            else
            {
                o.Append("        self.").Append(c.Name).Append(".place(x=").Append(c.X)
                    .Append(", y=").Append(c.Y).Append(", width=").Append(c.Width)
                    .Append(", height=").Append(c.Height).Append(")\n");
            }

            List<GuiControl> kids;
            if (childrenOf.TryGetValue(c.Id, out kids))
                foreach (GuiControl kid in kids)
                    EmitControlAndChildren(o, kid, "self." + c.Name, byId, childrenOf);
        }

        public string Emit(GuiForm form, string existingSource)
        {
            Dictionary<string, string> regions = CodeRegionPreserver.Parse(existingSource);

            bool usesTtk = false;
            foreach (GuiControl c in form.Controls)
            {
                string ns, ctor;
                CtorFor(c.Kind, out ns, out ctor);
                if (ns == "ttk") { usesTtk = true; break; }
            }

            StringBuilder o = new StringBuilder();
            o.Append("# AUTO-GENERATED by HelixPython. Edit only inside `# region UserCode-*` blocks.\n");
            o.Append("import tkinter as tk\n");
            if (usesTtk) o.Append("from tkinter import ttk\n");
            // Only when something on the form needs it, so a form built from Tk's own widgets
            // emits exactly the module it did before this support existed.
            List<string> runtimeImports = TkinterRuntime.ImportsFor(form);
            if (runtimeImports.Count > 0)
                o.Append("from ").Append(TkinterRuntime.ModuleName).Append(" import ")
                    .Append(string.Join(", ", runtimeImports.ToArray())).Append("\n");
            EmitCustomComponentImports(o, form);
            o.Append("\n\n");
            o.Append("class ").Append(form.FormClassName).Append("(tk.Frame):\n");
            o.Append("    def __init__(self, master=None):\n");
            o.Append("        super().__init__(master)\n");
            o.Append("        if self.master is not None:\n");
            o.Append("            self.master.title('").Append(EmitterCommon.PyEscape(form.Title)).Append("')\n");
            o.Append("            self.master.geometry('").Append(form.Width).Append("x").Append(form.Height).Append("')\n");
            o.Append("        self.pack(fill='both', expand=True)\n");
            o.Append("        self._build_ui()\n");
            o.Append("        self._wire_events()\n");
            o.Append("\n");

            o.Append("    def _build_ui(self):\n");
            if (form.Controls.Count == 0)
            {
                o.Append("        pass\n\n");
            }
            else
            {
                var byId = new Dictionary<string, GuiControl>(System.StringComparer.Ordinal);
                foreach (GuiControl c in form.Controls)
                    if (!string.IsNullOrEmpty(c.Id)) byId[c.Id] = c;
                List<GuiControl> roots;
                Dictionary<string, List<GuiControl>> childrenOf = BuildChildrenMap(form.Controls, out roots);
                foreach (GuiControl root in roots)
                    EmitControlAndChildren(o, root, "self", byId, childrenOf);
                o.Append("\n");
            }

            o.Append("    def _wire_events(self):\n");
            bool anyEvent = false;
            foreach (GuiControl c in form.Controls)
            {
                foreach (GuiEvent e in c.Events)
                {
                    if (string.IsNullOrEmpty(e.HandlerName)) continue;
                    anyEvent = true;
                    if (e.EventName == "command")
                        o.Append("        self.").Append(c.Name).Append(".config(command=self.").Append(e.HandlerName).Append(")\n");
                    else
                        o.Append("        self.").Append(c.Name).Append(".bind('").Append(EmitterCommon.PyEscape(e.EventName))
                            .Append("', self.").Append(e.HandlerName).Append(")\n");
                }
            }
            if (!anyEvent) o.Append("        pass\n");
            o.Append("\n");

            HashSet<string> emittedHandlers = new HashSet<string>(System.StringComparer.Ordinal);
            foreach (GuiControl c in form.Controls)
            {
                foreach (GuiEvent e in c.Events)
                {
                    if (string.IsNullOrEmpty(e.HandlerName)) continue;
                    if (!emittedHandlers.Add(e.HandlerName)) continue;
                    string regionName = "UserCode-" + e.HandlerName;
                    bool isCommand = e.EventName == "command";
                    string defaultBody = isCommand
                        ? "    def " + e.HandlerName + "(self):\n        pass\n\n"
                        : "    def " + e.HandlerName + "(self, event=None):\n        pass\n\n";
                    o.Append("    # region ").Append(regionName).Append("\n");
                    o.Append(CodeRegionPreserver.GetOrDefault(regions, regionName, defaultBody));
                    o.Append("    # endregion\n\n");
                }
            }

            {
                string regionName = "UserCode-main";
                string defaultBody =
                    "if __name__ == '__main__':\n" +
                    "    root = tk.Tk()\n" +
                    "    " + form.FormClassName + "(root)\n" +
                    "    root.mainloop()\n";
                o.Append("# region ").Append(regionName).Append("\n");
                o.Append(CodeRegionPreserver.GetOrDefault(regions, regionName, defaultBody));
                o.Append("# endregion\n");
            }

            return o.ToString();
        }
    }
