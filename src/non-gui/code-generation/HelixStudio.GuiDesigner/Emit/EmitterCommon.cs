namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using System.Collections.Generic;
    using System.Text;
    using HelixPythonNamespace.GuiDesigner.Model;

    /// <summary>Shared emitter helpers. Port of the C++ <c>emitter_common</c>.</summary>
    public static class EmitterCommon
    {
        public static string PyEscape(string s)
        {
            if (s == null) return "";
            StringBuilder outSb = new StringBuilder(s.Length + 2);
            foreach (char c in s)
            {
                if (c == '\\') outSb.Append("\\\\");
                else if (c == '\'') outSb.Append("\\'");
                else if (c == '\n') outSb.Append("\\n");
                else if (c == '\r') outSb.Append("\\r");
                else if (c == '\t') outSb.Append("\\t");
                else outSb.Append(c);
            }
            return outSb.ToString();
        }

        public static string PropOr(GuiControl c, string key, string fallback = "")
        {
            string v;
            if (c.Props.TryGetValue(key, out v) && !string.IsNullOrEmpty(v)) return v;
            return fallback;
        }

        public static int IntPropOr(GuiControl c, string key, int fallback)
        {
            string v;
            if (!c.Props.TryGetValue(key, out v) || string.IsNullOrEmpty(v)) return fallback;
            int parsed;
            // Mirror strtol: parse a leading integer, accept trailing junk.
            int i = 0;
            int sign = 1;
            if (i < v.Length && (v[i] == '+' || v[i] == '-')) { if (v[i] == '-') sign = -1; i++; }
            int start = i;
            long acc = 0;
            while (i < v.Length && v[i] >= '0' && v[i] <= '9') { acc = acc * 10 + (v[i] - '0'); i++; }
            if (i == start) return fallback; // no digits
            parsed = (int)(sign * acc);
            return parsed;
        }

        public static List<string> SplitCsv(string csv)
        {
            List<string> outList = new List<string>();
            if (csv == null) return outList;
            foreach (string raw in csv.Split(','))
            {
                string t = raw.Trim();
                if (t.Length > 0) outList.Add(t);
            }
            return outList;
        }

        public static string AutoGenBanner()
        {
            return "# AUTO-GENERATED by HelixPython. Edit only inside `# region UserCode-*` blocks.\n";
        }

        /// <summary>
        /// Product names this designer has stamped into generated files over the product's life.
        /// The banner is the ONLY signal that a file is designer-owned and therefore safe to
        /// overwrite without asking, so a rename must not orphan files an earlier build generated:
        /// the shell shipped as "HelixStudio", then briefly as "HelixPythonNamespace" (the
        /// mechanical namespace migration in a54c7b3 rewrote the literal too), and now as
        /// "HelixPython". Dropping the older two would make the designer treat its own output as
        /// hand-written code and start refusing to sync it.
        /// </summary>
        private static readonly string[] BannerProductNames = { "HelixPython", "HelixPythonNamespace", "HelixStudio" };

        /// <summary>
        /// True when <paramref name="content"/> opens with an emitter banner — the current one
        /// (<paramref name="currentMarker"/>) or any this product wrote under a former name.
        /// </summary>
        public static bool StartsWithAutoGeneratedBanner(string content, string currentMarker)
        {
            if (string.IsNullOrEmpty(content)) return false;
            string trimmed = content.TrimStart();
            if (!string.IsNullOrEmpty(currentMarker) &&
                trimmed.StartsWith(currentMarker, System.StringComparison.Ordinal)) return true;

            // The marker shape is "<comment-lead>AUTO-GENERATED by <Product>." or
            // "<comment-lead><auto-generated by <Product>>"; only the product token ever varied,
            // so probe the current marker's own prefix with each historical name substituted in.
            foreach (string product in BannerProductNames)
            {
                if (trimmed.StartsWith("# AUTO-GENERATED by " + product + ".", System.StringComparison.Ordinal)) return true;
                if (trimmed.StartsWith("// AUTO-GENERATED by " + product + ".", System.StringComparison.Ordinal)) return true;
                if (trimmed.StartsWith("// <auto-generated by " + product + ">", System.StringComparison.Ordinal)) return true;
            }
            return false;
        }

        public static string SafeMember(string name)
        {
            if (string.IsNullOrEmpty(name)) return "widget";
            StringBuilder outSb = new StringBuilder(name.Length + 2);
            if (name[0] >= '0' && name[0] <= '9') outSb.Append("c_");
            foreach (char c in name)
            {
                if ((c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_')
                    outSb.Append(c);
                else
                    outSb.Append('_');
            }
            return outSb.ToString();
        }

        public static string EventTokenForHandler(string eventName)
        {
            StringBuilder outSb = new StringBuilder(eventName.Length);
            foreach (char c in eventName)
            {
                if (c == '<' || c == '>' || c == '-') continue;
                outSb.Append(char.ToLowerInvariant(c));
            }
            return outSb.ToString();
        }
    }
}
