namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using HelixPythonNamespace.GuiDesigner.Model;

    /// <summary>Emits framework source for a <see cref="GuiForm"/>, preserving user-code regions.</summary>
    public interface IGuiCodeEmitter
    {
        // existingSource (may be empty) is the previous .py file's contents; the emitter
        // MUST preserve any `# region UserCode … # endregion` blocks found within it.
        string Emit(GuiForm form, string existingSource);
        string FrameworkName { get; }
        string SourceExtension { get; }
        string AutoGeneratedMarker { get; }
    }
}
