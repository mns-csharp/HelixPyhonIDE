namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using System.Collections.Generic;
    using System.Text.RegularExpressions;

    /// <summary>
    /// Extracts <c># region NAME … # endregion</c> handler bodies from previously-generated
    /// source so a regen can copy the user's edits back verbatim. Port of the C++
    /// <c>CodeRegionPreserver</c>.
    /// </summary>
    public static class CodeRegionPreserver
    {
        /// <summary>
        /// A region opener is a line whose first non-blank text is <c># region</c>.
        ///
        /// <para>
        /// The <c>^[ \t]*</c> anchor is not tidiness, it is the fix for silent data loss. Without
        /// it the pattern matched ANY occurrence of the words, including the one in the banner
        /// every generated file starts with:
        /// </para>
        /// <code>
        /// # AUTO-GENERATED by HelixPython. Edit only inside `# region UserCode-*` blocks.
        /// </code>
        /// <para>
        /// That line opened a region named <c>UserCode-*` blocks.</c> whose lazy body then ran to
        /// the first real <c># endregion</c> — swallowing the whole of the FIRST handler's region.
        /// The next regeneration found no entry for that handler and wrote the default <c>pass</c>
        /// over the user's code. Every form with at least one event handler lost its first
        /// handler's body, every time, with nothing reported. Reproduced on a 62-control form: of
        /// five regions filled, four came back.
        /// </para>
        /// <para>
        /// <c>Multiline</c> is what makes <c>^</c> mean "start of a line" rather than "start of the
        /// input"; <c>Singleline</c> is still needed so the body's <c>.</c> spans newlines. The two
        /// options are unrelated despite the names, and both are required.
        /// </para>
        /// </summary>
        private static readonly Regex RegionRe = new Regex(
            @"^[ \t]*#\s*region\s+([^\r\n]+)\r?\n(.*?)^[ \t]*#\s*endregion",
            RegexOptions.Singleline | RegexOptions.Multiline | RegexOptions.Compiled);

        public static Dictionary<string, string> Parse(string source)
        {
            Dictionary<string, string> outMap = new Dictionary<string, string>();
            if (string.IsNullOrEmpty(source)) return outMap;
            foreach (Match m in RegionRe.Matches(source))
            {
                string name = m.Groups[1].Value;
                string body = m.Groups[2].Value;
                name = name.TrimEnd(' ', '\t', '\r', '\n');
                outMap[name] = body; // last occurrence wins
            }
            return outMap;
        }

        public static string GetOrDefault(Dictionary<string, string> regions, string regionName, string defaultBody)
        {
            string body;
            return regions.TryGetValue(regionName, out body) ? body : defaultBody;
        }
    }
}
