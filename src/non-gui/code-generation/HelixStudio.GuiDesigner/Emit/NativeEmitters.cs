namespace HelixPythonNamespace.GuiDesigner.Emit
{
    using System;
    using System.Collections.Generic;
    using System.Text;
    using HelixPythonNamespace.GuiDesigner.Model;

    internal static class NativeEmitterCommon
    {
        internal static string Escape(string value)
        {
            return (value ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", "\\n");
        }

        internal static string Text(GuiControl control)
        {
            string value;
            if (control.Props.TryGetValue("Text", out value)) return value ?? "";
            if (control.Props.TryGetValue("text", out value)) return value ?? "";
            return control.Name;
        }

        internal static string Preserve(string existing, string begin, string end, string fallback)
        {
            if (!string.IsNullOrEmpty(existing))
            {
                int a = existing.IndexOf(begin, StringComparison.Ordinal);
                if (a >= 0)
                {
                    int b = existing.IndexOf(end, a + begin.Length, StringComparison.Ordinal);
                    if (b >= 0) return existing.Substring(a + begin.Length, b - a - begin.Length).Trim('\r', '\n');
                }
            }
            return fallback;
        }
    }

    public sealed class CppWin32Emitter : IGuiCodeEmitter
    {
        public string FrameworkName { get { return "C++ Win32 API"; } }
        public string SourceExtension { get { return ".cpp"; } }
        public string AutoGeneratedMarker { get { return "// AUTO-GENERATED by HelixPython."; } }
        public string Emit(GuiForm form, string existingSource)
        {
            StringBuilder s = new StringBuilder(); s.AppendLine(AutoGeneratedMarker).AppendLine("#include <windows.h>").AppendLine();
            s.AppendLine("LRESULT CALLBACK WindowProc(HWND hwnd, UINT msg, WPARAM wp, LPARAM lp) {").AppendLine("    if (msg == WM_DESTROY) { PostQuitMessage(0); return 0; }").AppendLine("    return DefWindowProc(hwnd, msg, wp, lp);").AppendLine("}").AppendLine();
            s.AppendLine("int WINAPI wWinMain(HINSTANCE instance, HINSTANCE, PWSTR, int show) {").Append("    const wchar_t CLASS_NAME[] = L\"").Append(EmitterCommon.SafeMember(form.FormClassName)).AppendLine("\";")
             .AppendLine("    WNDCLASSW wc{}; wc.lpfnWndProc = WindowProc; wc.hInstance = instance; wc.lpszClassName = CLASS_NAME; RegisterClassW(&wc);")
             .Append("    HWND hwnd = CreateWindowExW(0, CLASS_NAME, L\"").Append(NativeEmitterCommon.Escape(form.Title)).Append("\", WS_OVERLAPPEDWINDOW, CW_USEDEFAULT, CW_USEDEFAULT, ").Append(form.Width).Append(", ").Append(form.Height).AppendLine(", nullptr, nullptr, instance, nullptr);");
            int id = 1000; foreach (GuiControl c in form.Controls) s.Append("    CreateWindowExW(0, L\"").Append(Win32Class(c.Kind)).Append("\", L\"").Append(NativeEmitterCommon.Escape(NativeEmitterCommon.Text(c))).Append("\", WS_CHILD | WS_VISIBLE").Append(Win32Style(c.Kind)).Append(", ").Append(c.X).Append(", ").Append(c.Y).Append(", ").Append(c.Width).Append(", ").Append(c.Height).Append(", hwnd, reinterpret_cast<HMENU>(static_cast<INT_PTR>(").Append(id++).AppendLine(")), instance, nullptr);");
            s.AppendLine("    // region UserCode").AppendLine(NativeEmitterCommon.Preserve(existingSource, "// region UserCode", "// endregion", "    // Add initialization here.")).AppendLine("    // endregion")
             .AppendLine("    ShowWindow(hwnd, show); MSG message{}; while (GetMessage(&message, nullptr, 0, 0)) { TranslateMessage(&message); DispatchMessage(&message); } return 0;").AppendLine("}"); return s.ToString();
        }
        private static string Win32Class(GuiControlKind k) { switch (k) { case GuiControlKind.Label: return "STATIC"; case GuiControlKind.TextBox: return "EDIT"; case GuiControlKind.ListBox: return "LISTBOX"; case GuiControlKind.ComboBox: return "COMBOBOX"; default: return "BUTTON"; } }
        private static string Win32Style(GuiControlKind k) { if (k == GuiControlKind.CheckBox) return " | BS_AUTOCHECKBOX"; if (k == GuiControlKind.RadioButton) return " | BS_AUTORADIOBUTTON"; return ""; }
    }
}
