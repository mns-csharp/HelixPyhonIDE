namespace HelixPythonNamespace.Cli.Tests
{
    using System;
    using System.Collections.Generic;
    using System.Globalization;
    using System.IO;
    using System.Linq;
    using Microsoft.VisualStudio.TestTools.UnitTesting;
    using HelixPythonNamespace.Cli;

    /// <summary>
    /// The two structure verbs: <c>helix_cli dssp</c> and <c>helix_cli query</c>.
    ///
    /// They live on helix_cli rather than the launcher because the split is by object — the
    /// launcher takes a SOLUTION and executes it, helix_cli takes a PATH and reports on it. Both of
    /// these take a path. (The submission plan wrote them as <c>helixstudio dssp</c>, which would
    /// have put an analysis verb on the execution surface.)
    ///
    /// What they are for is reproducibility: a figure that can be regenerated by one command line
    /// is a figure a reviewer can check. So the assertions here are about the OUTPUT being usable —
    /// parseable CSV with the query in it — not merely about exit codes.
    /// </summary>
    [TestClass]
    public class StructureCliTests
    {
        private static readonly string GeneratedFixtures = CreateGeneratedFixtures();
        private readonly List<string> _temporary = new List<string>();

        [TestCleanup]
        public void TearDown()
        {
            foreach (string dir in _temporary)
            {
                try { if (Directory.Exists(dir)) Directory.Delete(dir, true); } catch (IOException) { }
            }
        }

        private sealed class RunResult
        {
            public int ExitCode;
            public string Out;
            public string Err;
        }

        private static RunResult Run(params string[] args)
        {
            var o = new StringWriter();
            var e = new StringWriter();
            int rc = CliRunner.Run(new List<string>(args), o, e);
            return new RunResult { ExitCode = rc, Out = o.ToString(), Err = e.ToString() };
        }

        private static string Fixture(string name)
        {
            return Path.Combine(GeneratedFixtures, name);
        }

        private static string CreateGeneratedFixtures()
        {
            string root = Path.Combine(Path.GetTempPath(), "helix-cli-fixtures-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(root);
            string[] atoms =
            {
                "ATOM      1  N   LYS A   1       0.000   0.000   0.000  1.00 20.00           N",
                "ATOM      2  CA  LYS A   1       1.450   0.000   0.000  1.00 20.00           C",
                "ATOM      3  C   LYS A   1       2.000   1.400   0.000  1.00 20.00           C",
                "ATOM      4  O   LYS A   1       1.500   2.400   0.000  1.00 20.00           O",
                "ATOM      5  N   ALA A   2       3.300   1.400   0.500  1.00 20.00           N",
                "ATOM      6  CA  ALA A   2       3.900   2.700   0.500  1.00 20.00           C",
                "ATOM      7  C   ALA A   2       5.400   2.500   0.500  1.00 20.00           C",
                "ATOM      8  O   ALA A   2       6.000   3.500   0.500  1.00 20.00           O",
                "ATOM      9  N   GLY A   3       6.100   1.300   1.000  1.00 20.00           N",
                "ATOM     10  CA  GLY A   3       7.500   1.000   1.000  1.00 20.00           C",
                "ATOM     11  C   GLY A   3       8.000  -0.400   1.000  1.00 20.00           C",
                "ATOM     12  O   GLY A   3       7.500  -1.400   1.000  1.00 20.00           O",
            };
            foreach (string file in new[] { "1ubq.pdb", "5i55.pdb" })
                File.WriteAllLines(Path.Combine(root, file), atoms.Concat(new[] { "TER", "END" }));
            File.WriteAllBytes(Path.Combine(root, "1ubq.dcd"), new byte[0]);
            return root;
        }

        /// <summary>A scratch directory holding copies of the named fixtures.</summary>
        private string Sandbox(params string[] fixtures)
        {
            string dir = Path.Combine(Path.GetTempPath(), "helix-cli-pdb-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            _temporary.Add(dir);
            foreach (string name in fixtures)
                File.Copy(Fixture(name), Path.Combine(dir, name));
            return dir;
        }

        // ---- dssp ------------------------------------------------------------------------------

        [TestMethod]
        public void DsspWritesAnAssignmentBesideEveryStructureInAFolder()
        {
            string dir = Sandbox("1ubq.pdb", "5i55.pdb");

            RunResult r = Run("dssp", dir, "--quiet");

            Assert.AreEqual(0, r.ExitCode, r.Err);
            Assert.IsTrue(File.Exists(Path.Combine(dir, "1ubq.dssp")), "1ubq.dssp should be written");
            Assert.IsTrue(File.Exists(Path.Combine(dir, "5i55.dssp")), "5i55.dssp should be written");
            StringAssert.Contains(r.Out, "2 structures, 2 assigned, 0 failed");

            StringAssert.Contains(r.Out, "3 residues");
        }

        [TestMethod]
        public void TheWrittenDsspIsARealAssignment()
        {
            string dir = Sandbox("1ubq.pdb");
            Assert.AreEqual(0, Run("dssp", dir, "--quiet").ExitCode);

            string[] lines = File.ReadAllLines(Path.Combine(dir, "1ubq.dssp"));
            Assert.IsTrue(lines.Length > 3, "one row per residue plus the header block");
            Assert.IsTrue(lines.Any(l => l.IndexOf("KABSCH", StringComparison.OrdinalIgnoreCase) >= 0
                                      || l.IndexOf("SANDER", StringComparison.OrdinalIgnoreCase) >= 0),
                "the file should carry the DSSP header it always has");
        }

        [TestMethod]
        public void ReferenceModeIsReportedSoAComparisonCanBeTrusted()
        {
            // --reference is DsspOptions.ReferenceCompatible(): the seven switches set the way
            // mkdssp sets them. Which mode produced a file matters more than the file, because the
            // whole point of the flag is diffing against another program's output.
            string dir = Sandbox("1ubq.pdb");

            RunResult plain = Run("dssp", Path.Combine(dir, "1ubq.pdb"), "--json", "--quiet");
            RunResult reference = Run("dssp", Path.Combine(dir, "1ubq.pdb"), "--reference", "--json", "--quiet");

            StringAssert.Contains(plain.Out, "\"reference_mode\":false");
            StringAssert.Contains(reference.Out, "\"reference_mode\":true");
            Assert.AreEqual(0, reference.ExitCode, reference.Err);
        }

        [TestMethod]
        public void DsspOnAMissingPathIsAUsageError()
        {
            RunResult r = Run("dssp", Path.Combine(Path.GetTempPath(), "no-such-" + Guid.NewGuid().ToString("N")));
            Assert.AreEqual(2, r.ExitCode);
            StringAssert.Contains(r.Err, "no such file or directory");
        }

        // ---- query -----------------------------------------------------------------------------

        [TestMethod]
        public void AnAggregateQueryPrintsOneValueAndItsSampleSize()
        {
            RunResult r = Run("query", Fixture("1ubq.pdb"), "--sql=select avg(beta) from atoms", "--quiet");

            Assert.AreEqual(0, r.ExitCode, r.Err);
            StringAssert.Contains(r.Out, "# query: select avg(beta) from atoms");
            StringAssert.Contains(r.Out, "value,matched_atoms");

            string[] cells = r.Out.Split('\n').Last(l => l.Length > 0).Split(',');
            Assert.IsTrue(double.Parse(cells[0], CultureInfo.InvariantCulture) > 0);
            Assert.AreEqual(12, int.Parse(cells[1], CultureInfo.InvariantCulture));
        }

        [TestMethod]
        public void AGroupedQueryPrintsATable()
        {
            RunResult r = Run("query", Fixture("1ubq.pdb"),
                              "--sql=select count(*) from atoms group by ss", "--quiet");

            Assert.AreEqual(0, r.ExitCode, r.Err);
            StringAssert.Contains(r.Out, "ss,count,atoms");

            var counts = r.Out.Split('\n')
                .Where(l => l.Length > 0 && !l.StartsWith("#") && !l.StartsWith("ss,"))
                .Select(l => long.Parse(l.Split(',')[2], CultureInfo.InvariantCulture))
                .ToArray();
            Assert.IsTrue(counts.Length >= 1);
            Assert.AreEqual(12L, counts.Sum(), "the groups partition the synthetic structure");
        }

        [TestMethod]
        public void ASelectionPrintsTheAtomsItMatched()
        {
            RunResult r = Run("query", Fixture("1ubq.pdb"), "--sql=chain='A' and resi=1", "--quiet");

            Assert.AreEqual(0, r.ExitCode, r.Err);
            StringAssert.Contains(r.Out, "index,name,resn,resi,chain,element,occupancy,beta,x,y,z");

            string[] rows = r.Out.Split('\n')
                .Where(l => l.Length > 0 && !l.StartsWith("#") && !l.StartsWith("index,")).ToArray();
            Assert.AreEqual(4, rows.Length, "the synthetic LYS residue has four atoms");
            foreach (string row in rows) StringAssert.Contains(row, ",LYS,1,A,");
        }

        [TestMethod]
        public void MalformedTrajectoryIsRejected()
        {
            RunResult r = Run("query", Fixture("1ubq.dcd"), "--sql=select avg(rg) from atoms", "--quiet");

            Assert.AreEqual(1, r.ExitCode);
        }

        [TestMethod]
        public void AQueryThatDoesNotCompileIsAUsageError()
        {
            RunResult r = Run("query", Fixture("1ubq.pdb"), "--sql=select avg(nope) from atoms", "--quiet");

            Assert.AreEqual(2, r.ExitCode, "a bad query is the caller's mistake, not a failed run");
            StringAssert.Contains(r.Err, "nope");
        }

        [TestMethod]
        public void QueryWithNoStatementSaysWhatToWrite()
        {
            RunResult r = Run("query", Fixture("1ubq.pdb"), "--quiet");

            Assert.AreEqual(2, r.ExitCode);
            StringAssert.Contains(r.Err, "--sql=");
            StringAssert.Contains(r.Err, "select avg(rg)", "the message should show a working example");
        }

        [TestMethod]
        public void BothVerbsAreListedInTheUsage()
        {
            RunResult r = Run();
            StringAssert.Contains(r.Out, "helix_cli dssp");
            StringAssert.Contains(r.Out, "helix_cli query");
            StringAssert.Contains(r.Out, "--reference");
        }
    }
}
