namespace HelixPythonNamespace.GuiDesigner.Tests
{
    using Microsoft.VisualStudio.TestTools.UnitTesting;
    using HelixPythonNamespace.GuiDesigner.Emit;
    using HelixPythonNamespace.GuiDesigner.Model;
    using HelixPythonNamespace.GuiDesigner.Parse;

    [TestClass]
    public class TkinterLayoutImporterTests
    {
        private static GuiForm SampleForm()
        {
            var f = new GuiForm { FormClassName = "LoginForm", Title = "Login", Width = 420, Height = 260, Framework = GuiFramework.Tkinter };
            f.Controls.Add(new GuiControl { Id = "l1", Kind = GuiControlKind.Label, Name = "userLabel", X = 30, Y = 30, Width = 90, Height = 24, Props = { ["Text"] = "Username" } });
            f.Controls.Add(new GuiControl { Id = "t1", Kind = GuiControlKind.TextBox, Name = "userText", X = 140, Y = 28, Width = 220, Height = 26 });
            f.Controls.Add(new GuiControl
            {
                Id = "b1",
                Kind = GuiControlKind.Button,
                Name = "loginButton",
                X = 140,
                Y = 156,
                Width = 100,
                Height = 30,
                Props = { ["Text"] = "Log In" },
                Events = { new GuiEvent { EventName = "command", HandlerName = "on_login_click" } },
            });
            return f;
        }

        [TestMethod]
        public void RoundTrips_TheEmitterOwnShape()
        {
            GuiForm original = SampleForm();
            string py = new TkinterEmitter().Emit(original, "");

            GuiForm imported = TkinterLayoutImporter.TryImport(py, "LoginForm");

            Assert.IsNotNull(imported, "a form generated by this emitter must always import back");
            Assert.AreEqual("LoginForm", imported.FormClassName);
            Assert.AreEqual("Login", imported.Title);
            Assert.AreEqual(420, imported.Width);
            Assert.AreEqual(260, imported.Height);
            Assert.AreEqual(3, imported.Controls.Count);

            GuiControl userText = imported.Controls[1];
            Assert.AreEqual(GuiControlKind.TextBox, userText.Kind);
            Assert.AreEqual(140, userText.X);
            Assert.AreEqual(28, userText.Y);
            Assert.AreEqual(220, userText.Width);
            Assert.AreEqual(26, userText.Height);

            GuiControl loginButton = imported.Controls[2];
            Assert.AreEqual("Log In", loginButton.Props["Text"]);
            Assert.AreEqual(1, loginButton.Events.Count);
            Assert.AreEqual("on_login_click", loginButton.Events[0].HandlerName);
        }

        [TestMethod]
        public void RoundTrip_PreservesEditsAcrossASecondImportEmitCycle()
        {
            GuiForm original = SampleForm();
            string py1 = new TkinterEmitter().Emit(original, "");
            GuiForm reopened = TkinterLayoutImporter.TryImport(py1, "LoginForm");
            Assert.IsNotNull(reopened);

            GuiControl button = reopened.Controls[2];
            button.X = 200;
            button.Y = 300;

            string py2 = new TkinterEmitter().Emit(reopened, py1);
            GuiForm reopenedAgain = TkinterLayoutImporter.TryImport(py2, "LoginForm");

            Assert.IsNotNull(reopenedAgain);
            Assert.AreEqual(200, reopenedAgain.Controls[2].X);
            Assert.AreEqual(300, reopenedAgain.Controls[2].Y);
        }

        // Mirrors the actual fixture that motivated this feature: a tk.Tk subclass (window IS self,
        // no self.master), a ttk.Notebook held in a LOCAL variable (not self.notebook), and two
        // instances of locally-imported custom classes composed as tabs via .add(...).
        [TestMethod]
        public void ImportsNotebookWithComposedCustomPanels_FromHandWrittenCode()
        {
            string source =
                "import tkinter as tk\n" +
                "from tkinter import ttk\n" +
                "from app_gui.views import AnimalPanel, ShapePanel\n\n" +
                "class MainWindow(tk.Tk):\n" +
                "    def __init__(self) -> None:\n" +
                "        super().__init__()\n" +
                "        self.title(\"HelixStudio GUI demo\")\n" +
                "        self.geometry(\"420x320\")\n\n" +
                "        notebook = ttk.Notebook(self)\n" +
                "        notebook.pack(fill=\"both\", expand=True)\n\n" +
                "        self.shape_panel = ShapePanel(notebook)\n" +
                "        notebook.add(self.shape_panel, text=\"Shapes\")\n\n" +
                "        self.animal_panel = AnimalPanel(notebook)\n" +
                "        notebook.add(self.animal_panel, text=\"Animals\")\n";

            GuiForm imported = TkinterLayoutImporter.TryImport(source, "MainWindow");

            Assert.IsNotNull(imported, "a Notebook + composed custom panels must be importable");
            Assert.AreEqual("MainWindow", imported.FormClassName);
            Assert.AreEqual("HelixStudio GUI demo", imported.Title);
            Assert.AreEqual(420, imported.Width);
            Assert.AreEqual(320, imported.Height);
            Assert.AreEqual(3, imported.Controls.Count);

            GuiControl notebook = imported.Controls[0];
            Assert.AreEqual(GuiControlKind.TabControl, notebook.Kind);
            Assert.AreEqual("notebook", notebook.Name);
            Assert.AreEqual("Pack", notebook.Props["Layout"]);
            Assert.AreEqual("both", notebook.Props["PackFill"]);

            GuiControl shapePanel = imported.Controls[1];
            Assert.AreEqual(GuiControlKind.CustomComponent, shapePanel.Kind);
            Assert.AreEqual("shape_panel", shapePanel.Name);
            Assert.AreEqual("ShapePanel", shapePanel.Props["ClassName"]);
            Assert.AreEqual("app_gui.views", shapePanel.Props["Module"]);
            Assert.AreEqual(notebook.Id, shapePanel.ParentId);
            Assert.AreEqual("Shapes", shapePanel.Props["TabTitle"]);

            GuiControl animalPanel = imported.Controls[2];
            Assert.AreEqual("AnimalPanel", animalPanel.Props["ClassName"]);
            Assert.AreEqual(notebook.Id, animalPanel.ParentId);
            Assert.AreEqual("Animals", animalPanel.Props["TabTitle"]);
        }

        // The imported model must re-emit as valid, equivalent Tkinter — proving the "load, modify,
        // persist back" loop actually closes for this composed shape, not just that parsing succeeds.
        [TestMethod]
        public void ImportedNotebookForm_ReEmitsWithTabsAndCustomImports()
        {
            string source =
                "import tkinter as tk\n" +
                "from tkinter import ttk\n" +
                "from app_gui.views import AnimalPanel, ShapePanel\n\n" +
                "class MainWindow(tk.Tk):\n" +
                "    def __init__(self) -> None:\n" +
                "        super().__init__()\n" +
                "        self.title(\"HelixStudio GUI demo\")\n" +
                "        self.geometry(\"420x320\")\n" +
                "        notebook = ttk.Notebook(self)\n" +
                "        notebook.pack(fill=\"both\", expand=True)\n" +
                "        self.shape_panel = ShapePanel(notebook)\n" +
                "        notebook.add(self.shape_panel, text=\"Shapes\")\n";

            GuiForm imported = TkinterLayoutImporter.TryImport(source, "MainWindow");
            Assert.IsNotNull(imported);

            string regenerated = new TkinterEmitter().Emit(imported, "");
            Assert.IsTrue(regenerated.Contains("from app_gui.views import ShapePanel"), regenerated);
            Assert.IsTrue(regenerated.Contains("self.notebook = ttk.Notebook(self)"), regenerated);
            Assert.IsTrue(regenerated.Contains("self.shape_panel = ShapePanel(self.notebook)"), regenerated);
            Assert.IsTrue(regenerated.Contains("self.notebook.add(self.shape_panel, text='Shapes')"), regenerated);
        }

        // Regression test: a pack(fill='both', expand=True)-managed widget (like the Notebook in the
        // real fixture) has no explicit width/height in the source — before this fix it kept the
        // generic 120x28 default, rendering as a sliver in the corner of an otherwise-empty form.
        [TestMethod]
        public void PackFilledNotebook_GetsASizeThatFillsTheForm_NotTheGenericDefault()
        {
            string source =
                "import tkinter as tk\n" +
                "from tkinter import ttk\n\n" +
                "class MainWindow(tk.Tk):\n" +
                "    def __init__(self) -> None:\n" +
                "        super().__init__()\n" +
                "        self.geometry(\"420x320\")\n" +
                "        notebook = ttk.Notebook(self)\n" +
                "        notebook.pack(fill=\"both\", expand=True)\n";

            GuiForm imported = TkinterLayoutImporter.TryImport(source, "MainWindow");
            Assert.IsNotNull(imported);

            GuiControl notebook = imported.Controls[0];
            Assert.IsTrue(notebook.Width > 300, "notebook width should approximate the 420-wide form, not the 120 default: " + notebook.Width);
            Assert.IsTrue(notebook.Height > 200, "notebook height should approximate the 320-tall form, not the 28 default: " + notebook.Height);
        }

        [TestMethod]
        public void HandWrittenCodeWithNoRecognizableWidgets_DoesNotImport()
        {
            string source =
                "class Empty:\n" +
                "    def __init__(self):\n" +
                "        self.value = compute_something()\n";
            Assert.IsNull(TkinterLayoutImporter.TryImport(source, "Empty"));
        }

        [TestMethod]
        public void EmptyOrNullSource_ReturnsNull()
        {
            Assert.IsNull(TkinterLayoutImporter.TryImport(null, "Foo"));
            Assert.IsNull(TkinterLayoutImporter.TryImport("", "Foo"));
            Assert.IsNull(TkinterLayoutImporter.TryImport("   \n  ", "Foo"));
        }
    }
}
